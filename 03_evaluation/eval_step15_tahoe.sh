#!/bin/bash
#SBATCH --job-name=s15_eval
#SBATCH --partition=condo
#SBATCH -q a2s2
#SBATCH --gres=gpu:h100:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=48G
#SBATCH --time=08:00:00
#SBATCH --array=0-44
#SBATCH --output=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s15ev_%A_%a.out
#SBATCH --error=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s15ev_%A_%a.err
# Step 15b (Tahoe brain/gut) evaluation under PREREG_step15b_tahoe_model.md section 9: one task per checkpoint,
# same decode as training: task T -> split = T / 15, arm = (T % 15) / 3 (base, recipe, guidance_w2, attn_cross,
# mlp_ctrl), seed = T % 3. Development split first: sbatch --array=15-29 (drug_split_1); confirmation splits
# afterwards: sbatch --array=0-14,30-44.
#   base        : leakage_test_base_tahoe.py  (DDPM checkpoint; the sampler's DDIM path, as the sci-Plex base was scored)
#   others      : leakage_test_fm_tahoe.py <split> <ckpt> <tag> fm_gaussian 50 euler   (Gaussian-source flow matching, 50 NFE)
#   guidance_w2 : same, with S12_GUIDANCE_W=2 S12_GUIDE_TMIN=0.0 at sampling time
# Both harness files are GENERATED from the frozen sci-Plex harness by port_harness_step15.py (paired control = same
# line AND plate; outputs in tahoe_results/); per-cell storage on; MAX_CELLS_PER_COND=200 as on sci-Plex.
# DRYRUN=1 SLURM_ARRAY_TASK_ID=<T> bash eval_step15_tahoe.sh  runs every guard and the sidecar check, then stops.
# Post: condition count == data record n_test_conditions for the split; finite, non-negative predictions; sampler
# prints match the arm; provenance/s15ev_<TAG>.json with sha256 of every input and output.
set -eo pipefail
module load cuda/12.2.0
source /share/apps/NYUAD5/miniconda/3-4.11.0/etc/profile.d/conda.sh
conda activate /scratch/ni2071/conda_envs/squidiff
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export SQUIDIFF_SAVE_PER_CELL=1
export S12_GUIDE_TMIN=0.0
W=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff
cd "$W"
NFE=50; PREREG=PREREG_step15b_tahoe_model.md; RECORD=tahoe_results/step15_data_record.json

T=$SLURM_ARRAY_TASK_ID
case "$T" in *[!0-9]*|"") echo "FATAL: non-numeric task id: $T"; exit 1 ;; esac
if [ "$T" -gt 44 ]; then echo "FATAL: task out of range (0-44): $T"; exit 1; fi

# --- pre-registration, scripts and sampler sources committed and clean ---
N=$(grep -c '^## ' $PREREG)
if [ "$N" -lt 9 ]; then echo "FATAL: prereg has $N sections, expected at least 9"; exit 1; fi
TRACKED="$PREREG port_harness_step15.py leakage_test_base_tahoe.py leakage_test_fm_tahoe.py eval_step15_tahoe.sh score_step15_tahoe.py finalize_step15.py"
for f in $TRACKED; do git ls-files --error-unmatch $f >/dev/null 2>&1 || { echo "FATAL: $f not committed (PREREG section 9)"; exit 1; }; done
git diff --quiet -- $TRACKED leakage_test_base_sciplex_array.py leakage_test_fm_sciplex.py sample_squidiff.py Squidiff \
  || { echo "FATAL: prereg, harness, scorer or sampler sources uncommitted"; exit 1; }
[ -s "$RECORD" ] || { echo "FATAL: missing data record $RECORD"; exit 1; }
# the generated harness files must be current: their header names the source sha256
python - <<'PY'
import hashlib, re, sys
for src, dst in (('leakage_test_base_sciplex_array.py', 'leakage_test_base_tahoe.py'), ('leakage_test_fm_sciplex.py', 'leakage_test_fm_tahoe.py')):
    head = open(dst).read(400)
    m = re.search(r'GENERATED by port_harness_step15.py from (\S+) \(sha256 ([0-9a-f]{64})\)', head)
    if not m or m.group(1) != src: sys.exit('FATAL: %s lacks a valid generated header' % dst)
    if m.group(2) != hashlib.sha256(open(src, 'rb').read()).hexdigest(): sys.exit('FATAL: %s is stale: %s changed since the port' % (dst, src))
print('[port] generated harness files are current')
PY
COMMIT=$(git rev-parse HEAD)

# --- decode the task (identical to train_step15_tahoe.sh) ---
SPLIT_IDX=$(( T / 15 )); WITHIN=$(( T % 15 )); ARM_IDX=$(( WITHIN / 3 )); SEED=$(( WITHIN % 3 ))
SPLIT=drug_split_${SPLIT_IDX}
GW=none; ADALN=True; FM=gaussian; CDROP=0.0; EARM=mlp; ARCH=adaLN-Zero
case $ARM_IDX in
  0) ARM=base;        ADALN=False; FM=none; ARCH=base; EXPECT=54221060 ;;
  1) ARM=recipe;      EXPECT=58178180 ;;
  2) ARM=guidance_w2; CDROP=0.1; GW=2; EXPECT=58178180 ;;
  3) ARM=attn_cross;  EARM=attn_cross; EXPECT=58532804 ;;
  4) ARM=mlp_ctrl;    EARM=mlp_ctrl;   EXPECT=58532300 ;;
  *) echo "FATAL: bad arm index $ARM_IDX"; exit 1 ;;
esac
export ARM SPLIT SEED EARM ADALN FM CDROP GW EXPECT ARCH
CKPT=$W/step15/${ARM}/${SPLIT}_seed_${SEED}/model_0.9999.pt
SIDE=${CKPT}.encoding.json
PROV_TR=$W/provenance/s15tr_${SPLIT}_${ARM}_seed_${SEED}.json
TAG=s15_${SPLIT}_${ARM}_seed_${SEED}
PROV=$W/provenance/s15ev_${TAG}.json
export CKPT SIDE PROV_TR TAG PROV RECORD SPLIT_IDX NFE PREREG COMMIT
for f in "$CKPT" "$SIDE" "$PROV_TR"; do [ -s "$f" ] || { echo "FATAL: missing $f"; exit 1; }; done
for f in tahoe_results/vectors_${TAG}.npz tahoe_results/vectors_${TAG}_pc.npz tahoe_results/leakage_${TAG}.json "$PROV"; do
  [ -e "$f" ] && { echo "FATAL: output exists: $f"; exit 1; }
done
EXPECT_N=$(python -c "import json; print(json.load(open('$RECORD'))['splits']['$SPLIT_IDX']['n_test_conditions'])")
export EXPECT_N
export MASTER_PORT=$(( 20000 + T ))

# --- sidecar consistent with the task and bound to the certified checkpoint ---
python - <<'PY'
import hashlib, json, os, sys
e = os.environ
s = json.load(open(e['SIDE'])); p = json.load(open(e['PROV_TR']))
want = dict(arm=e['ARM'], split=e['SPLIT'], seed=int(e['SEED']), encoder_arm=e['EARM'], use_adaln=(e['ADALN'] == 'True'),
            fm_source=e['FM'], cond_drop=float(e['CDROP']), drug_encoding='fingerprint', memory_size=0, n_params=int(e['EXPECT']))
for k, v in want.items():
    if s.get(k) != v: sys.exit('FATAL: sidecar %s=%r, task expects %r' % (k, s.get(k), v))
if p.get('status') != 'completed' or p.get('tag') != '%s_%s_seed_%s' % (e['SPLIT'], e['ARM'], e['SEED']):
    sys.exit('FATAL: training provenance is not a completed record for this task: %s' % e['PROV_TR'])
h = hashlib.sha256()
with open(e['CKPT'], 'rb') as f:
    for c in iter(lambda: f.read(1 << 24), b''): h.update(c)
if h.hexdigest() != p.get('checkpoint_sha256'): sys.exit('FATAL: checkpoint sha256 differs from the certified one in %s' % e['PROV_TR'])
print('[sidecar] arm=%s split=%s seed=%s encoder_arm=%s use_adaln=%s n_params=%s trained_at=%s  checkpoint bound' % (s['arm'], s['split'], s['seed'], s['encoder_arm'], s['use_adaln'], s['n_params'], str(s.get('commit'))[:7]))
PY

echo "[prereg] $N sections committed | [commit] $COMMIT | [node] $(hostname)"
echo "[task] T=$T  $TAG  arm=$ARM  expect_conditions=$EXPECT_N  guidance=$GW  nfe=$NFE"
if [ "${DRYRUN:-0}" = "1" ]; then echo "[dryrun] guards passed for $TAG; nothing run"; exit 0; fi
if [ "$ARM" = base ]; then
  unset S12_GUIDANCE_W
  python -u leakage_test_base_tahoe.py "$SPLIT" "$CKPT" "$TAG"
else
  if [ "$GW" = none ]; then unset S12_GUIDANCE_W; else export S12_GUIDANCE_W=$GW; fi
  python -u leakage_test_fm_tahoe.py "$SPLIT" "$CKPT" "$TAG" fm_gaussian "$NFE" euler
fi

# --- post: outputs complete and consistent; sampler prints match the arm; provenance ---
python - <<'PY'
import datetime, hashlib, json, os, re, subprocess, sys
import numpy as np
e = os.environ
tag = e['TAG']; expect_n = int(e['EXPECT_N'])
v = 'tahoe_results/vectors_%s.npz' % tag; pc = 'tahoe_results/vectors_%s_pc.npz' % tag; js = 'tahoe_results/leakage_%s.json' % tag
for f in (v, pc, js):
    if not os.path.isfile(f) or os.path.getsize(f) == 0: sys.exit('FATAL: missing or empty ' + f)
d = np.load(v, allow_pickle=True)
n = len(d['cond'])
if n != expect_n: sys.exit('FATAL: %d conditions, data record expects %d for %s' % (n, expect_n, e['SPLIT']))
if len(set(map(str, d['cond']))) != n: sys.exit('FATAL: duplicate condition labels')
for k in ('true', 'A', 'B', 'C'):
    if not np.all(np.isfinite(d[k])): sys.exit('FATAL: non-finite %s' % k)
if float(np.asarray(d['B']).min()) < 0: sys.exit('FATAL: negative predicted expression')
p = np.load(pc, allow_pickle=True)
if len(p['pred']) != expect_n: sys.exit('FATAL: per-cell file has %d conditions' % len(p['pred']))
nc = [int(np.asarray(a).shape[0]) for a in p['pred']]
if max(nc) > 200: sys.exit('FATAL: per-cell population larger than the 200-cell cap: %d' % max(nc))
log = open('logger_files/s15ev_%s_%s.out' % (e['SLURM_ARRAY_JOB_ID'], e['SLURM_ARRAY_TASK_ID'])).read()
m = re.search(r'encoder arm detected from checkpoint: (\S+) \(memory_size=(\d+)\)', log)
if not m: sys.exit('FATAL: the sampler did not print the detected encoder arm')
if m.group(1) != e['EARM'] or int(m.group(2)) != 0: sys.exit('FATAL: sampler detected arm %s memory_size %s, task expects %s 0' % (m.group(1), m.group(2), e['EARM']))
a = re.search(r'checkpoint architecture: (\S+)', log)
if not a or a.group(1) != e['ARCH']: sys.exit('FATAL: sampler architecture %r, task expects %r' % (a.group(1) if a else None, e['ARCH']))
de = re.search(r'drug encoding detected from checkpoint: (\S+)', log)
if not de or de.group(1) != 'fingerprint': sys.exit('FATAL: sampler drug encoding %r' % (de.group(1) if de else None))
gw_seen = None
if e['ARM'] != 'base':
    g = re.search(r'\[step12\] guidance_w=(\S+)', log)
    if not g: sys.exit('FATAL: the FM sampler did not print its guidance setting')
    gw_seen = g.group(1)
    if e['GW'] == 'none' and gw_seen != 'None': sys.exit('FATAL: guidance_w=%s for an unguided arm' % gw_seen)
    if e['GW'] != 'none' and (gw_seen == 'None' or abs(float(gw_seen) - float(e['GW'])) > 1e-9): sys.exit('FATAL: guidance_w=%s, task expects %s' % (gw_seen, e['GW']))
sha = lambda q: hashlib.sha256(open(q, 'rb').read()).hexdigest()
side = json.load(open(e['SIDE'])); tr = json.load(open(e['PROV_TR']))
rec = dict(status='completed', tag=tag, task=int(e['SLURM_ARRAY_TASK_ID']), slurm_array_job=e['SLURM_ARRAY_JOB_ID'],
           split=e['SPLIT'], arm=e['ARM'], seed=int(e['SEED']), encoder_arm=e['EARM'], use_adaln=(e['ADALN'] == 'True'),
           fm_source=e['FM'], cond_drop=float(e['CDROP']), drug_encoding='fingerprint', n_params=side['n_params'],
           sampler=('ddim' if e['ARM'] == 'base' else 'euler_ode'), nfe=(None if e['ARM'] == 'base' else int(e['NFE'])),
           guidance_w=(None if e['GW'] == 'none' else float(e['GW'])), guide_t_min=0.0, max_cells_per_cond=200,
           n_conditions=n, cells_min=min(nc), cells_max=max(nc), expect_conditions=expect_n,
           prereg=e['PREREG'], commit=e['COMMIT'], training_commit=side.get('commit'), training_provenance=e['PROV_TR'],
           checkpoint=e['CKPT'], checkpoint_sha256=tr['checkpoint_sha256'],
           vectors_npz=v, vectors_sha256=sha(v), per_cell_npz=pc, per_cell_sha256=sha(pc), leakage_json=js, leakage_sha256=sha(js),
           data_record=e['RECORD'], data_record_sha256=sha(e['RECORD']),
           harness_base_sha256=sha('leakage_test_base_tahoe.py'), harness_fm_sha256=sha('leakage_test_fm_tahoe.py'),
           harness_src_sha256=sha('leakage_test_base_sciplex_array.py'), fm_src_sha256=sha('leakage_test_fm_sciplex.py'),
           sampler_sha256=sha('sample_squidiff.py'), flow_matching_sha256=sha('Squidiff/flow_matching.py'),
           node=subprocess.run('hostname', shell=True, capture_output=True, text=True).stdout.strip(),
           completed_at=datetime.datetime.now(datetime.timezone.utc).isoformat())
json.dump(rec, open(e['PROV'], 'w'), indent=2)
print('[post] %s: %d conditions (record %d), cells %d-%d, finite, non-negative, arm %s / %s bound, guidance %s' % (tag, n, expect_n, min(nc), max(nc), e['EARM'], e['ARCH'], gw_seen))
PY
echo "[$(date)] $TAG DONE"
