#!/bin/bash
#SBATCH --job-name=s18_eval
#SBATCH --partition=condo
#SBATCH -q a2s2
#SBATCH --gres=gpu:h100:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=48G
#SBATCH --time=08:00:00
#SBATCH --array=0-17
#SBATCH --output=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s18ev_%A_%a.out
#SBATCH --error=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s18ev_%A_%a.err
# Step 18 evaluation under PREREG_step18_tahoe_ot_pairing.md section 3: 18 tasks.
#   T = 0-8  : the ot_pair checkpoints,  split = T / 3, seed = T % 3        (tag s18_<split>_ot_pair_seed_<k>)
#   T = 9-17 : the Step 15b RECIPE checkpoints re-evaluated under the Step 18 harness, U = T - 9, split = U / 3, seed = U % 3
#              (tag s18r_<split>_recipe_seed_<k>; provenance s18rv_*). Their mean vectors and generated cells must reproduce
#              the Step 15b arrays (true, C, cond bitwise; B and the per-cell populations within 1e-3) - the harness change
#              is output-only - and their per-cell files carry the conditioning control cells for section 4.4.
#   development first:  sbatch --array=3-5,12-14 eval_step18_tahoe.sh     confirmation:  sbatch --array=0-2,6-11,15-17 eval_step18_tahoe.sh
# Every run: leakage_test_fm_step18.py <split> <ckpt> <tag> fm_gaussian 50 euler, unguided, per-cell storage on,
# MAX_CELLS_PER_COND=200 - the Step 15b procedure. leakage_test_fm_step18.py is GENERATED from leakage_test_fm_tahoe.py by
# port_harness_step18.py; the only change is that the per-cell file also stores the Protocol-B control cells (`ctrl`).
# DRYRUN=1 SLURM_ARRAY_TASK_ID=<T> bash eval_step18_tahoe.sh runs the guards and stops.
set -eo pipefail
module load cuda/12.2.0
source /share/apps/NYUAD5/miniconda/3-4.11.0/etc/profile.d/conda.sh
conda activate /scratch/ni2071/conda_envs/squidiff
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export SQUIDIFF_SAVE_PER_CELL=1
export S12_GUIDE_TMIN=0.0
unset S12_GUIDANCE_W SQUIDIFF_DRUG_ENCODING
W=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff
cd "$W"
NFE=50; PREREG=PREREG_step18_tahoe_ot_pairing.md; RECORD=tahoe_results/step15_data_record.json; OTREC=tahoe_results/ot_pairing_check.json

T=$SLURM_ARRAY_TASK_ID
case "$T" in *[!0-9]*|"") echo "FATAL: non-numeric task id: $T"; exit 1 ;; esac
if [ "$T" -gt 17 ]; then echo "FATAL: task out of range (0-17): $T"; exit 1; fi

# --- pre-registration, scripts, harness and sampler sources committed and clean ---
N=$(grep -c '^## ' $PREREG)
if [ "$N" -lt 9 ]; then echo "FATAL: prereg has $N sections, expected at least 9"; exit 1; fi
TRACKED="$PREREG port_harness_step18.py leakage_test_fm_step18.py port_harness_step15.py leakage_test_base_tahoe.py leakage_test_fm_tahoe.py eval_step18_tahoe.sh score_step18_tahoe.py finalize_step18.py check_ot_pairing_tahoe.py $RECORD $OTREC"
for f in $TRACKED; do git ls-files --error-unmatch $f >/dev/null 2>&1 || { echo "FATAL: $f not committed (PREREG section 9)"; exit 1; }; done
git diff --quiet -- $TRACKED leakage_test_base_sciplex_array.py leakage_test_fm_sciplex.py sample_squidiff.py train_squidiff.py Squidiff \
  || { echo "FATAL: prereg, harness, scorer, sampler or encoder sources uncommitted"; exit 1; }
[ -s "$RECORD" ] || { echo "FATAL: missing data record $RECORD"; exit 1; }
python - <<'PY'
import hashlib, re, sys
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
for gen, src, dst in (('port_harness_step15.py', 'leakage_test_base_sciplex_array.py', 'leakage_test_base_tahoe.py'),
                      ('port_harness_step15.py', 'leakage_test_fm_sciplex.py', 'leakage_test_fm_tahoe.py'),
                      ('port_harness_step18.py', 'leakage_test_fm_tahoe.py', 'leakage_test_fm_step18.py')):
    head = open(dst).read(400)
    m = re.search(r'GENERATED by %s from (\S+) \(sha256 ([0-9a-f]{64})\)' % re.escape(gen), head)
    if not m or m.group(1) != src: sys.exit('FATAL: %s lacks a valid generated header from %s' % (dst, gen))
    if m.group(2) != sha(src): sys.exit('FATAL: %s is stale: %s changed since the port' % (dst, src))
if "_PC.setdefault('ctrl', [])" not in open('leakage_test_fm_step18.py').read(): sys.exit('FATAL: leakage_test_fm_step18.py lacks the ctrl storage')
print('[port] generated harness files are current; ctrl storage present')
PY
COMMIT=$(git rev-parse HEAD)

# --- decode the task ---
if [ "$T" -le 8 ]; then
  KIND=ot; SPLIT_IDX=$(( T / 3 )); SEED=$(( T % 3 )); ARM=ot_pair
  SPLIT=drug_split_${SPLIT_IDX}
  CKPT=$W/step18/${ARM}/${SPLIT}_seed_${SEED}/model_0.9999.pt
  PROV_TR=$W/provenance/s18tr_${SPLIT}_${ARM}_seed_${SEED}.json
  TAG=s18_${SPLIT}_${ARM}_seed_${SEED}
  PROV=$W/provenance/s18ev_${TAG}.json
else
  KIND=recipe; U=$(( T - 9 )); SPLIT_IDX=$(( U / 3 )); SEED=$(( U % 3 )); ARM=recipe
  SPLIT=drug_split_${SPLIT_IDX}
  PROV_TR=$W/provenance/s15tr_${SPLIT}_${ARM}_seed_${SEED}.json
  [ -s "$PROV_TR" ] || { echo "FATAL: missing Step 15b training provenance $PROV_TR"; exit 1; }
  CKPT=$(python -c "import json; print(json.load(open('$PROV_TR'))['checkpoint'])")
  TAG=s18r_${SPLIT}_${ARM}_seed_${SEED}
  PROV=$W/provenance/s18rv_${TAG}.json
fi
SIDE=${CKPT}.encoding.json
export KIND ARM SPLIT SEED SPLIT_IDX CKPT SIDE PROV_TR TAG PROV RECORD OTREC NFE PREREG COMMIT
for f in "$CKPT" "$PROV_TR"; do [ -s "$f" ] || { echo "FATAL: missing $f"; exit 1; }; done
for f in tahoe_results/vectors_${TAG}.npz tahoe_results/vectors_${TAG}_pc.npz tahoe_results/leakage_${TAG}.json "$PROV"; do
  [ -e "$f" ] && { echo "FATAL: output exists: $f"; exit 1; }
done
EXPECT_N=$(python -c "import json; print(json.load(open('$RECORD'))['splits']['$SPLIT_IDX']['n_test_conditions'])")
export EXPECT_N
export MASTER_PORT=$(( 24000 + T ))

# --- the checkpoint is the certified one; for ot_pair the sidecar and the OT control pin match the task ---
python - <<'PY'
import hashlib, json, os, sys
e = os.environ
p = json.load(open(e['PROV_TR']))
if p.get('status') != 'completed' or p.get('split') != e['SPLIT'] or int(p.get('seed', -1)) != int(e['SEED']) or p.get('arm') != e['ARM']:
    sys.exit('FATAL: training provenance %s is not a completed record for arm %s split %s seed %s' % (e['PROV_TR'], e['ARM'], e['SPLIT'], e['SEED']))
h = hashlib.sha256()
with open(e['CKPT'], 'rb') as f:
    for c in iter(lambda: f.read(1 << 24), b''): h.update(c)
if h.hexdigest() != p.get('checkpoint_sha256'): sys.exit('FATAL: checkpoint sha256 differs from the certified one in %s' % e['PROV_TR'])
if e['KIND'] == 'ot':
    s = json.load(open(e['SIDE']))
    want = dict(arm='ot_pair', split=e['SPLIT'], seed=int(e['SEED']), encoder_arm='mlp', use_adaln=True, fm_source='gaussian', cond_drop=0.0,
                drug_encoding='fingerprint', drug_dimension=1024, memory_size=0)
    for k, v in want.items():
        if s.get(k) != v: sys.exit('FATAL: sidecar %s=%r, task expects %r' % (k, s.get(k), v))
    ot = json.load(open(e['OTREC']))
    if p.get('control_ot_sha256') != ot['written'][e['SPLIT']]['sha256']: sys.exit('FATAL: the run\'s OT control pin differs from the pairing record')
    print('[sidecar] ot_pair split=%s seed=%s n_params=%s trained_at=%s | OT control pin %s' % (s['split'], s['seed'], s['n_params'], str(s.get('commit'))[:7], p['control_ot_sha256'][:12]))
else:
    print('[recipe] Step 15b checkpoint %s (sha256 %s) re-evaluated under the Step 18 harness' % (e['CKPT'], p['checkpoint_sha256'][:12]))
PY

echo "[prereg] $N sections committed | [commit] $COMMIT | [node] $(hostname)"
echo "[task] T=$T  $TAG  kind=$KIND  arm=$ARM  split=$SPLIT  seed=$SEED  expect_conditions=$EXPECT_N  guidance=none  nfe=$NFE"
if [ "${DRYRUN:-0}" = "1" ]; then echo "[dryrun] guards passed for $TAG; nothing run"; exit 0; fi
python -u leakage_test_fm_step18.py "$SPLIT" "$CKPT" "$TAG" fm_gaussian "$NFE" euler

# --- post: outputs complete and consistent; ctrl stored; recipe re-evaluations reproduce the Step 15b arrays; provenance ---
python - <<'PY'
import datetime, hashlib, json, os, re, subprocess, sys
import numpy as np
e = os.environ
tag = e['TAG']; expect_n = int(e['EXPECT_N'])
v = 'tahoe_results/vectors_%s.npz' % tag; pc = 'tahoe_results/vectors_%s_pc.npz' % tag; js = 'tahoe_results/leakage_%s.json' % tag
for f in (v, pc, js):
    if not os.path.isfile(f) or os.path.getsize(f) == 0: sys.exit('FATAL: missing or empty ' + f)
d = np.load(v, allow_pickle=True)
n = len(d['cond'])
if n != expect_n: sys.exit('FATAL: %d conditions, data record expects %d for %s' % (n, expect_n, e['SPLIT']))
if len(set(map(str, d['cond']))) != n: sys.exit('FATAL: duplicate condition labels')
for k in ('true', 'A', 'B', 'C'):
    if not np.all(np.isfinite(d[k])): sys.exit('FATAL: non-finite %s' % k)
if float(np.asarray(d['B']).min()) < 0: sys.exit('FATAL: negative predicted expression')
p = np.load(pc, allow_pickle=True)
if 'ctrl' not in p.files: sys.exit('FATAL: the per-cell file has no ctrl key')
pc_pred = p['pred']; pc_ctrl = p['ctrl']; pc_true = p['true']  # read each archive member ONCE: indexing p[k][i] inside a loop re-reads the whole member (O(n^2), no GPU; killed drug_split_1 for an idle GPU)
if len(pc_pred) != expect_n or len(pc_ctrl) != expect_n: sys.exit('FATAL: per-cell file has %d / %d conditions' % (len(pc_pred), len(pc_ctrl)))
nc = [int(np.asarray(a).shape[0]) for a in pc_pred]
if max(nc) > 200: sys.exit('FATAL: per-cell population larger than the 200-cell cap: %d' % max(nc))
for i in range(expect_n):
    if np.asarray(pc_ctrl[i]).shape != np.asarray(pc_pred[i]).shape: sys.exit('FATAL: ctrl and pred shapes differ in condition %d' % i)
    if not np.all(np.isfinite(np.asarray(pc_ctrl[i], np.float32))): sys.exit('FATAL: non-finite ctrl in condition %d' % i)
log = open('logger_files/s18ev_%s_%s.out' % (e['SLURM_ARRAY_JOB_ID'], e['SLURM_ARRAY_TASK_ID'])).read()
m = re.search(r'encoder arm detected from checkpoint: (\S+) \(memory_size=(\d+)\)', log)
if not m or m.group(1) != 'mlp' or int(m.group(2)) != 0: sys.exit('FATAL: sampler detected arm %r, task expects mlp 0' % (m.group(0) if m else None))
a = re.search(r'checkpoint architecture: (\S+)', log)
if not a or a.group(1) != 'adaLN-Zero': sys.exit('FATAL: sampler architecture %r, task expects adaLN-Zero' % (a.group(1) if a else None))
de = re.search(r'drug encoding detected from checkpoint: (\S+) \(drug_dimension=(\d+)\)', log)
if not de or de.group(1) != 'fingerprint' or int(de.group(2)) != 1024: sys.exit('FATAL: sampler drug encoding %r, task expects fingerprint (1024)' % (de.group(0) if de else None))
he = re.search(r'\[harness\] drug encoder = (\S+) \(drug_dimension=(\d+)\)', log)
if not he or he.group(1) != 'fingerprint' or int(he.group(2)) != 1024: sys.exit('FATAL: harness drug encoder %r, task expects fingerprint (1024)' % (he.group(0) if he else None))
if '[step18] harness stores the conditioning control cells' not in log: sys.exit('FATAL: the Step 18 harness did not print its ctrl line')
g = re.search(r'\[step12\] guidance_w=(\S+)', log)
if not g or g.group(1) != 'None': sys.exit('FATAL: guidance_w=%s for an unguided arm' % (g.group(1) if g else None))
sha = lambda q: hashlib.sha256(open(q, 'rb').read()).hexdigest()
tr = json.load(open(e['PROV_TR']))
repro = None
if e['KIND'] == 'recipe':
    ref = 'tahoe_results/vectors_s15_%s_recipe_seed_%s.npz' % (e['SPLIT'], e['SEED']); refpc = ref.replace('.npz', '_pc.npz')
    pj = json.load(open('provenance/s15ev_s15_%s_recipe_seed_%s.json' % (e['SPLIT'], e['SEED'])))
    if pj.get('vectors_sha256') != sha(ref) or pj.get('per_cell_sha256') != sha(refpc): sys.exit('FATAL: the Step 15b recipe arrays differ from their provenance')
    r = np.load(ref, allow_pickle=True); rp = np.load(refpc, allow_pickle=True)
    if not np.array_equal(np.array([str(x) for x in r['cond']]), np.array([str(x) for x in d['cond']])): sys.exit('FATAL: condition order differs from the Step 15b arrays')
    for k in ('true', 'C'):
        if not np.array_equal(np.asarray(r[k]), np.asarray(d[k])): sys.exit('FATAL: %s differs from the Step 15b arrays (data, must be bitwise equal)' % k)
    dB = float(np.abs(np.asarray(r['B'], np.float64) - np.asarray(d['B'], np.float64)).max())
    dA = float(np.abs(np.asarray(r['A'], np.float64) - np.asarray(d['A'], np.float64)).max())
    dP = 0.0
    rp_true = rp['true']; rp_pred = rp['pred']  # read each member ONCE (same O(n^2) fix as the pc_* hoist above)
    for i in range(expect_n):
        if not np.array_equal(np.asarray(rp_true[i], np.float32), np.asarray(pc_true[i], np.float32)): sys.exit('FATAL: stored real cells differ from the Step 15b per-cell file in condition %d' % i)
        a_, b_ = np.asarray(rp_pred[i], np.float64), np.asarray(pc_pred[i], np.float64)
        if a_.shape != b_.shape: sys.exit('FATAL: per-cell population shape differs from Step 15b in condition %d' % i)
        dP = max(dP, float(np.abs(a_ - b_).max()))
    if dB > 1e-3 or dP > 1e-3: sys.exit('FATAL: the re-evaluation differs from the Step 15b arrays (max |dB| %.2e, max |dpred| %.2e > 1e-3): the harness change is not output-only' % (dB, dP))
    repro = dict(reference_vectors=ref, reference_per_cell=refpc, max_abs_diff_B=dB, max_abs_diff_A=dA, max_abs_diff_pred=dP, true_C_cond_bitwise_equal=True, real_cells_bitwise_equal=True)
    print('[repro] %s reproduces the Step 15b arrays: true, C, cond, real cells bitwise; max |dB| %.2e, max |dA| %.2e, max |dpred| %.2e' % (tag, dB, dA, dP))
rec = dict(status='completed', tag=tag, kind=e['KIND'], task=int(e['SLURM_ARRAY_TASK_ID']), slurm_array_job=e['SLURM_ARRAY_JOB_ID'],
           split=e['SPLIT'], arm=e['ARM'], seed=int(e['SEED']), encoder_arm='mlp', use_adaln=True, fm_source='gaussian', cond_drop=0.0,
           drug_encoding='fingerprint', drug_dimension=1024, sampler='euler_ode', nfe=int(e['NFE']), guidance_w=None, guide_t_min=0.0, max_cells_per_cond=200,
           n_conditions=n, cells_min=min(nc), cells_max=max(nc), expect_conditions=expect_n, ctrl_stored=True,
           prereg=e['PREREG'], commit=e['COMMIT'], training_commit=tr.get('commit'), training_provenance=e['PROV_TR'],
           checkpoint=e['CKPT'], checkpoint_sha256=tr['checkpoint_sha256'], control_ot_sha256=tr.get('control_ot_sha256'),
           vectors_npz=v, vectors_sha256=sha(v), per_cell_npz=pc, per_cell_sha256=sha(pc), leakage_json=js, leakage_sha256=sha(js),
           data_record=e['RECORD'], data_record_sha256=sha(e['RECORD']), pairing_record=e['OTREC'], pairing_record_sha256=sha(e['OTREC']),
           harness_sha256=sha('leakage_test_fm_step18.py'), harness_src_sha256=sha('leakage_test_fm_tahoe.py'), harness_base_sha256=sha('leakage_test_base_tahoe.py'),
           sampler_sha256=sha('sample_squidiff.py'), datasets_sha256=sha('Squidiff/scrna_datasets.py'), flow_matching_sha256=sha('Squidiff/flow_matching.py'),
           reproduction=repro, node=subprocess.run('hostname', shell=True, capture_output=True, text=True).stdout.strip(),
           completed_at=datetime.datetime.now(datetime.timezone.utc).isoformat())
json.dump(rec, open(e['PROV'], 'w'), indent=2)
print('[post] %s: %d conditions (record %d), cells %d-%d, finite, non-negative, ctrl stored, fingerprint bound by sampler and harness, unguided' % (tag, n, expect_n, min(nc), max(nc)))
PY
echo "[$(date)] $TAG DONE"
