#!/usr/bin/env python3
"""
port_harness_step24.py - generates leakage_test_fm_step24.py from the Step 15b Tahoe harness.

Purpose
-------
Step 24 asks whether the rewired recipe still identifies a held-out compound when handed a different compound's
fingerprint (PREREG_step24_fingerprint_swap.md sections 2 and 3). The substitution happens at sampling time, so no
model is trained and the Step 15b checkpoints are used unchanged. As in Steps 15, 16 and 18, the harness is not
edited in place: this script writes a new file whose header names its source and that source's sha256, which the
launcher re-checks before every run.

Logic
-----
1. Reads leakage_test_fm_tahoe.py, confirms it is the file generated by port_harness_step15.py, and records its
   sha256.
2. Replaces exactly one block - the encoder shim (the `Drug_dose_encoder` function that shadows the harness's own
   import) - with a version that reads S24_MODE:
     off (default) : behaves exactly as the Step 15b shim
     shuf          : every SMILES is replaced by the SMILES of the structure the committed derangement pairs it
                     with, then encoded as usual, so dose scaling is applied to the substituted fingerprint
     zero          : the fingerprint is zeroed after encoding
   The substituting shim stops the run if a SMILES is not in the permutation, if the permutation file does not match
   its own recorded sha256, or if it belongs to another split; and at process exit it prints how many distinct
   SMILES were actually substituted, which the launcher asserts equals the structure count.
3. Writes leakage_test_fm_step24.py, then verifies structurally that nothing else changed: removing the inserted
   block and the generated header from the output restores the source file byte for byte.
Nothing else in the harness, the sampler or the Squidiff package is touched.

Run from the worktree root (CPU, seconds):
    python port_harness_step24.py
    python port_harness_step24.py --force      # regenerate over an existing file
"""
import argparse
import hashlib
import os
import sys

SRC = "leakage_test_fm_tahoe.py"
DST = "leakage_test_fm_step24.py"
HEADER = "# GENERATED by port_harness_step24.py from %s (sha256 %s) -- do not edit; re-run the port script.\n"

ANCHOR = '''def Drug_dose_encoder(drug_SMILES_list, dose_list, comb_num=1, num_Bits=1024):
    """Shadows the harness's import so the encoding matches the checkpoint."""
    return DRUG_ENCODERS[_name](drug_SMILES_list, dose_list, comb_num)
'''

BLOCK = '''# ---------------------------------------------------------------- Step 24: compound substitution at sampling time
# PREREG_step24_fingerprint_swap.md sections 2 and 3. The checkpoint, the encoding name inferred from its width and
# every launcher assertion are untouched: only the SMILES handed to the encoder changes, or the fingerprint is
# zeroed afterwards. A substituted fingerprint has the same 1,024 columns as the real one.
#   S24_MODE unset or 'off' : identical to the Step 15b harness
#   S24_MODE=shuf           : each held-out structure receives another held-out structure's SMILES, under the
#                             committed derangement (tahoe_results/step24/permutation.json; sha256 re-checked here)
#   S24_MODE=zero           : the fingerprint is all zeros (no compound information at all)
import atexit as _s24_atexit, hashlib as _s24_hl, json as _s24_js
S24_MODE = _os.environ.get('S24_MODE', 'off') or 'off'
if S24_MODE not in ('off', 'shuf', 'zero'):
    sys.exit('FATAL: S24_MODE must be off, shuf or zero, got %r' % S24_MODE)
_S24_MAP, _S24_SEEN, _S24_CALLS = {}, set(), [0]
if S24_MODE != 'off':
    # every substituting run reports how often the model's encoder went through this shim, so a run in which
    # the shim was bypassed (and the model saw real fingerprints) cannot pass the launcher's post-check
    _s24_atexit.register(lambda: print('[step24] encoder calls through the substituting shim: %d' % _S24_CALLS[0]))
if S24_MODE == 'shuf':
    _s24_file = _os.environ.get('S24_PERMUTATION', 'tahoe_results/step24/permutation.json')
    _s24_p = _s24_js.load(open(_s24_file))
    _s24_sids = _s24_p['structures']
    _s24_want = _s24_hl.sha256('\\n'.join('%s>%s' % (k, _s24_p['map'][k]) for k in _s24_sids).encode()).hexdigest()
    if _s24_want != _s24_p['sha256']:
        sys.exit('FATAL: %s does not match its own recorded sha256' % _s24_file)
    if _s24_p.get('split') != SPLIT:
        sys.exit('FATAL: %s is for split %r, this run is %r' % (_s24_file, _s24_p.get('split'), SPLIT))
    for _s24_s in _s24_sids:
        _s24_own = _s24_p['smiles'][_s24_s]['own']
        _s24_sub = _s24_p['smiles'][_s24_s]['substituted']
        if _s24_own == _s24_sub:
            sys.exit('FATAL: structure %s would keep its own SMILES' % _s24_s)
        if _S24_MAP.setdefault(_s24_own, _s24_sub) != _s24_sub:
            sys.exit('FATAL: the SMILES of structure %s is mapped two ways' % _s24_s)
    print('[step24] mode=shuf  %d structures substituted  permutation sha256 %s'
          % (len(_S24_MAP), _s24_p['sha256'][:12]))
    _s24_atexit.register(lambda: print('[step24] distinct SMILES substituted during the run: %d of %d'
                                       % (len(_S24_SEEN), len(_S24_MAP))))
else:
    print('[step24] mode=%s' % S24_MODE)


def Drug_dose_encoder(drug_SMILES_list, dose_list, comb_num=1, num_Bits=1024):
    """Shadows the harness's import so the encoding matches the checkpoint (Step 24: with the substitution)."""
    _S24_CALLS[0] += 1
    if S24_MODE == 'shuf':
        _s24_out = []
        for _s24_smi in drug_SMILES_list:
            if _s24_smi not in _S24_MAP:
                sys.exit('FATAL: a SMILES reached the encoder that is not in the Step 24 permutation: %s'
                         % str(_s24_smi)[:80])
            _S24_SEEN.add(_s24_smi)
            _s24_out.append(_S24_MAP[_s24_smi])
        drug_SMILES_list = _s24_out
    _s24_fp = DRUG_ENCODERS[_name](drug_SMILES_list, dose_list, comb_num)
    if S24_MODE == 'zero':
        _s24_fp = np.zeros_like(np.asarray(_s24_fp, dtype=float))
    return _s24_fp
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--dst", default=DST)
    ap.add_argument("--force", action="store_true", help="regenerate over an existing output")
    a = ap.parse_args()
    if os.path.exists(a.dst) and not a.force:
        sys.exit("FATAL: %s exists (use --force to regenerate)" % a.dst)
    src = open(a.src).read()
    if "GENERATED by port_harness_step15.py" not in src[:400]:
        sys.exit("FATAL: %s is not the harness generated by port_harness_step15.py" % a.src)
    if src.count(ANCHOR) != 1:
        sys.exit("FATAL: the encoder shim was found %d times in %s (expected once)" % (src.count(ANCHOR), a.src))
    digest = hashlib.sha256(open(a.src, "rb").read()).hexdigest()
    head = HEADER % (a.src, digest)
    out = head + src.replace(ANCHOR, BLOCK)
    open(a.dst, "w").write(out)

    # structural check: removing the header and the inserted block must restore the source exactly
    back = open(a.dst).read()
    if not back.startswith(head):
        sys.exit("FATAL: the generated file does not start with its header")
    back = back[len(head):]
    if back.count(BLOCK) != 1:
        sys.exit("FATAL: the inserted block is not present exactly once in the output")
    if back.replace(BLOCK, ANCHOR) != src:
        sys.exit("FATAL: the generated file differs from the source outside the inserted block")
    print("[port] %s -> %s" % (a.src, a.dst))
    print("[port] source sha256 %s" % digest)
    print("[port] one block replaced; the rest of the file is byte-identical to the source")
    print("[port] generated sha256 %s" % hashlib.sha256(open(a.dst, "rb").read()).hexdigest())


if __name__ == "__main__":
    main()
