#!/bin/bash
#SBATCH --job-name=s24_eval
#SBATCH --partition=condo
#SBATCH -q a2s2
#SBATCH --gres=gpu:h100:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=48G
#SBATCH --time=08:00:00
#SBATCH --array=0-6
#SBATCH --output=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff_ms/logger_files/s24ev_%A_%a.out
#SBATCH --error=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff_ms/logger_files/s24ev_%A_%a.err
# Step 24 (fingerprint substitution) evaluation under PREREG_step24_fingerprint_swap.md section 8. Evaluation only:
# the Step 15b recipe checkpoints are used unchanged and no model is trained. One task per run:
#   T=0,1,2 -> fpshuf seed T        every held-out structure receives another's SMILES (committed derangement)
#   T=3,4,5 -> fpzero seed T-3      the fingerprint is all zeros
#   T=6     -> recipe_repro seed 0  the substitution switched off; must reproduce the Step 15b arrays bitwise
# Run T=6 FIRST and let its bitwise check pass before any arm run (prereg section 7 guard 3, section 8 step 3):
#   sbatch --array=6 eval_step24_tahoe.sh      then      sbatch --array=0-5 eval_step24_tahoe.sh
# The harness is leakage_test_fm_step24.py, generated by port_harness_step24.py from the Step 15b Tahoe harness;
# only its encoder shim differs, and the substitution is chosen by S24_MODE.
# DRYRUN=1 SLURM_ARRAY_TASK_ID=<T> bash eval_step24_tahoe.sh   runs every guard, then stops.
set -eo pipefail
module load cuda/12.2.0
source /share/apps/NYUAD5/miniconda/3-4.11.0/etc/profile.d/conda.sh
conda activate /scratch/ni2071/conda_envs/squidiff
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export SQUIDIFF_SAVE_PER_CELL=1
export S12_GUIDE_TMIN=0.0
unset S12_GUIDANCE_W                      # every Step 24 run is unguided, as the recipe is
W=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff_ms      # the manuscript worktree: code, records and outputs
CK=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff        # the main checkout: the Step 15b checkpoints
cd "$W"
NFE=50; SPLIT=drug_split_1; SPLIT_IDX=1
PREREG=PREREG_step24_fingerprint_swap.md
RECORD=tahoe_results/step15_data_record.json
PERM=tahoe_results/step24/permutation.json

T=$SLURM_ARRAY_TASK_ID
case "$T" in *[!0-9]*|"") echo "FATAL: non-numeric task id: $T"; exit 1 ;; esac
if [ "$T" -gt 6 ]; then echo "FATAL: task out of range (0-6): $T"; exit 1; fi

# --- pre-registration, scripts and sampler sources committed and clean ---
N=$(grep -c '^## ' $PREREG)
if [ "$N" -lt 9 ]; then echo "FATAL: prereg has $N sections, expected at least 9"; exit 1; fi
TRACKED="$PREREG port_harness_step24.py make_step24_permutation.py leakage_test_fm_step24.py eval_step24_tahoe.sh score_step24_tahoe.py run_step24_score.sh $PERM"
for f in $TRACKED; do git ls-files --error-unmatch $f >/dev/null 2>&1 || { echo "FATAL: $f not committed (PREREG section 8)"; exit 1; }; done
git diff --quiet HEAD -- $TRACKED leakage_test_fm_tahoe.py leakage_test_base_tahoe.py \
  leakage_test_base_sciplex_array.py leakage_test_fm_sciplex.py sample_squidiff.py Squidiff \
  || { echo "FATAL: prereg, harness, scorer or sampler sources differ from the last commit"; exit 1; }
[ -s "$RECORD" ] || { echo "FATAL: missing data record $RECORD"; exit 1; }

# --- the generated harness files are current, both links of the chain ---
python - <<'PY'
import hashlib, re, sys
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
for src, dst, port in (('leakage_test_fm_sciplex.py', 'leakage_test_fm_tahoe.py', 'port_harness_step15.py'),
                       ('leakage_test_base_sciplex_array.py', 'leakage_test_base_tahoe.py', 'port_harness_step15.py'),
                       ('leakage_test_fm_tahoe.py', 'leakage_test_fm_step24.py', 'port_harness_step24.py')):
    m = re.search(r'GENERATED by %s from (\S+) \(sha256 ([0-9a-f]{64})\)' % re.escape(port), open(dst).read(400))
    if not m or m.group(1) != src:
        sys.exit('FATAL: %s lacks a valid header naming %s' % (dst, src))
    if m.group(2) != sha(src):
        sys.exit('FATAL: %s is stale: %s changed since the port' % (dst, src))
print('[port] generated harness files are current (sciplex -> tahoe -> step24)')
PY

# --- the committed permutation is self-consistent and belongs to this split ---
export PERM RECORD SPLIT SPLIT_IDX
python - <<'PY'
import hashlib, json, os, sys
p = json.load(open(os.environ['PERM']))
sids = p['structures']
want = hashlib.sha256('\n'.join('%s>%s' % (k, p['map'][k]) for k in sids).encode()).hexdigest()
if want != p['sha256']:
    sys.exit('FATAL: the permutation record does not match its own sha256')
if p.get('split') != os.environ['SPLIT']:
    sys.exit('FATAL: the permutation is for split %r, this run is %r' % (p.get('split'), os.environ['SPLIT']))
rec = json.load(open(os.environ['RECORD']))
held = sorted(rec['splits'][os.environ['SPLIT_IDX']]['held_structures'])
if sids != held:
    sys.exit('FATAL: the permutation covers %d structures, the data record holds %d held-out' % (len(sids), len(held)))
if any(p['map'][k] == k for k in sids) or sorted(p['map'].values()) != sids:
    sys.exit('FATAL: the permutation is not a derangement of the held-out structures')
print('[permutation] %d held-out structures, derangement, sha256 %s' % (len(sids), p['sha256'][:12]))
PY
COMMIT=$(git rev-parse HEAD)

# --- decode the task: always the recipe checkpoint, the substitution varies ---
SEED=$(( T % 3 )); if [ "$T" = 6 ]; then SEED=0; fi
case $T in
  0|1|2) ARM=fpshuf;        S24_MODE=shuf ;;
  3|4|5) ARM=fpzero;        S24_MODE=zero ;;
  6)     ARM=recipe_repro;  S24_MODE=off  ;;
esac
EARM=mlp; ADALN=True; FM=gaussian; CDROP=0.0; ARCH=adaLN-Zero; EXPECT=58178180
export ARM S24_MODE SEED EARM ADALN FM CDROP EXPECT ARCH
CKPT=$CK/step15/recipe/${SPLIT}_seed_${SEED}/model_0.9999.pt
SIDE=${CKPT}.encoding.json
PROV_TR=$W/provenance/s15tr_${SPLIT}_recipe_seed_${SEED}.json
TAG=s24_${SPLIT}_${ARM}_seed_${SEED}
PROV=$W/provenance/s24ev_${TAG}.json
export CKPT SIDE PROV_TR TAG PROV NFE PREREG COMMIT
for f in "$CKPT" "$SIDE" "$PROV_TR"; do [ -s "$f" ] || { echo "FATAL: missing $f"; exit 1; }; done
for f in tahoe_results/vectors_${TAG}.npz tahoe_results/vectors_${TAG}_pc.npz tahoe_results/leakage_${TAG}.json "$PROV"; do
  [ -e "$f" ] && { echo "FATAL: output exists: $f"; exit 1; }
done
EXPECT_N=$(python -c "import json; print(json.load(open('$RECORD'))['splits']['$SPLIT_IDX']['n_test_conditions'])")
export EXPECT_N
export MASTER_PORT=$(( 21000 + T ))

# --- the sidecar is the certified recipe checkpoint for this seed ---
python - <<'PY'
import hashlib, json, os, sys
e = os.environ
s = json.load(open(e['SIDE'])); p = json.load(open(e['PROV_TR']))
want = dict(arm='recipe', split=e['SPLIT'], seed=int(e['SEED']), encoder_arm=e['EARM'], use_adaln=(e['ADALN'] == 'True'),
            fm_source=e['FM'], cond_drop=float(e['CDROP']), drug_encoding='fingerprint', memory_size=0, n_params=int(e['EXPECT']))
for k, v in want.items():
    if s.get(k) != v: sys.exit('FATAL: sidecar %s=%r, task expects %r' % (k, s.get(k), v))
if p.get('status') != 'completed' or p.get('tag') != '%s_recipe_seed_%s' % (e['SPLIT'], e['SEED']):
    sys.exit('FATAL: training provenance is not a completed recipe record for this seed: %s' % e['PROV_TR'])
h = hashlib.sha256()
with open(e['CKPT'], 'rb') as f:
    for c in iter(lambda: f.read(1 << 24), b''): h.update(c)
if h.hexdigest() != p.get('checkpoint_sha256'): sys.exit('FATAL: checkpoint sha256 differs from the certified one in %s' % e['PROV_TR'])
print('[sidecar] recipe split=%s seed=%s encoder_arm=%s n_params=%s trained_at=%s  checkpoint bound'
      % (s['split'], s['seed'], s['encoder_arm'], s['n_params'], str(s.get('commit'))[:7]))
PY

echo "[prereg] $N sections committed | [commit] $COMMIT | [node] $(hostname)"
echo "[task] T=$T  $TAG  arm=$ARM  S24_MODE=$S24_MODE  expect_conditions=$EXPECT_N  nfe=$NFE"
if [ "${DRYRUN:-0}" = "1" ]; then echo "[dryrun] guards passed for $TAG; nothing run"; exit 0; fi

export S24_MODE S24_PERMUTATION=$PERM
python -u leakage_test_fm_step24.py "$SPLIT" "$CKPT" "$TAG" fm_gaussian "$NFE" euler

# --- post: outputs complete, the substitution did what it claims, provenance ---
python - <<'PY'
import datetime, hashlib, json, os, re, subprocess, sys
import numpy as np
e = os.environ
tag = e['TAG']; expect_n = int(e['EXPECT_N'])
v = 'tahoe_results/vectors_%s.npz' % tag; pc = 'tahoe_results/vectors_%s_pc.npz' % tag; js = 'tahoe_results/leakage_%s.json' % tag
for f in (v, pc, js):
    if not os.path.isfile(f) or os.path.getsize(f) == 0: sys.exit('FATAL: missing or empty ' + f)
d = np.load(v, allow_pickle=True)
n = len(d['cond'])
if n != expect_n: sys.exit('FATAL: %d conditions, data record expects %d' % (n, expect_n))
if len(set(map(str, d['cond']))) != n: sys.exit('FATAL: duplicate condition labels')
for k in ('true', 'A', 'B', 'C'):
    if not np.all(np.isfinite(d[k])): sys.exit('FATAL: non-finite %s' % k)
if float(np.asarray(d['B']).min()) < 0: sys.exit('FATAL: negative predicted expression')
p = np.load(pc, allow_pickle=True)
p_pred0 = p['pred']                                   # read once
if len(p_pred0) != expect_n: sys.exit('FATAL: per-cell file has %d conditions' % len(p_pred0))
nc = [int(np.asarray(a).shape[0]) for a in p_pred0]
del p_pred0
if max(nc) > 200: sys.exit('FATAL: per-cell population larger than the 200-cell cap: %d' % max(nc))
log = open('logger_files/s24ev_%s_%s.out' % (e['SLURM_ARRAY_JOB_ID'], e['SLURM_ARRAY_TASK_ID'])).read()
m = re.search(r'encoder arm detected from checkpoint: (\S+) \(memory_size=(\d+)\)', log)
if not m or m.group(1) != e['EARM'] or int(m.group(2)) != 0:
    sys.exit('FATAL: sampler detected arm %r, task expects %s 0' % (m.groups() if m else None, e['EARM']))
a = re.search(r'checkpoint architecture: (\S+)', log)
if not a or a.group(1) != e['ARCH']: sys.exit('FATAL: sampler architecture %r' % (a.group(1) if a else None))
de = re.search(r'drug encoding detected from checkpoint: (\S+)', log)
if not de or de.group(1) != 'fingerprint': sys.exit('FATAL: sampler drug encoding %r' % (de.group(1) if de else None))
g = re.search(r'\[step12\] guidance_w=(\S+)', log)
if not g or g.group(1) != 'None': sys.exit('FATAL: guidance_w=%r, every Step 24 run is unguided' % (g.group(1) if g else None))
# --- Step 24's own checks on the substitution ---
md = re.search(r'\[step24\] mode=(\w+)', log)
if not md or md.group(1) != e['S24_MODE']:
    sys.exit('FATAL: the harness ran mode %r, task expects %r' % (md.group(1) if md else None, e['S24_MODE']))
perm_sha = None
if e['S24_MODE'] != 'off':
    nc_ = re.search(r'\[step24\] encoder calls through the substituting shim: (\d+)', log)
    if not nc_ or int(nc_.group(1)) == 0:
        sys.exit('FATAL: the encoder was not called through the Step 24 shim (calls: %s)' % (nc_.group(1) if nc_ else None))
    print('[step24] %s encoder calls went through the substituting shim' % nc_.group(1))
if e['S24_MODE'] == 'shuf':
    ns = re.search(r'\[step24\] mode=shuf  (\d+) structures substituted  permutation sha256 ([0-9a-f]{12})', log)
    seen = re.search(r'\[step24\] distinct SMILES substituted during the run: (\d+) of (\d+)', log)
    if not ns or not seen: sys.exit('FATAL: the harness did not report the substitution')
    if seen.group(1) != seen.group(2) or seen.group(1) != ns.group(1):
        sys.exit('FATAL: %s of %s structures were substituted; every held-out structure must be'
                 % (seen.group(1), seen.group(2)))
    perm = json.load(open(e['PERM']))
    if not perm['sha256'].startswith(ns.group(2)):
        sys.exit('FATAL: the harness used permutation %s, the committed record is %s' % (ns.group(2), perm['sha256'][:12]))
    perm_sha = perm['sha256']
    print('[step24] all %s held-out structures substituted under permutation %s' % (seen.group(1), ns.group(2)))
# the reproduction run must equal the committed Step 15b arrays bitwise (prereg section 7 guard 3)
repro = None
if e['ARM'] == 'recipe_repro':
    ref = 'tahoe_results/vectors_s15_%s_recipe_seed_%s.npz' % (e['SPLIT'], e['SEED'])
    if not os.path.isfile(ref): sys.exit('FATAL: missing the Step 15b reference %s' % ref)
    r = np.load(ref, allow_pickle=True)
    if not np.array_equal(np.array([str(x) for x in r['cond']]), np.array([str(x) for x in d['cond']])):
        sys.exit('FATAL: condition order differs from the Step 15b reference')
    dB = float(np.abs(np.asarray(d['B'], np.float64) - np.asarray(r['B'], np.float64)).max())
    worst = {k: float(np.abs(np.asarray(d[k], np.float64) - np.asarray(r[k], np.float64)).max()) for k in ('true', 'C', 'A')}
    rp = np.load('tahoe_results/vectors_s15_%s_recipe_seed_%s_pc.npz' % (e['SPLIT'], e['SEED']), allow_pickle=True)
    # each npz member is read ONCE: indexing p['true'][i] inside the loop would re-read the whole file per condition
    p_true, p_pred, r_true, r_pred = p['true'], p['pred'], rp['true'], rp['pred']
    cells_equal = (len(p_true) == len(r_true) == len(p_pred) == len(r_pred) == n
                   and all(np.array_equal(np.asarray(p_true[i]), np.asarray(r_true[i])) for i in range(n))
                   and all(np.array_equal(np.asarray(p_pred[i]), np.asarray(r_pred[i])) for i in range(n)))
    if dB != 0.0 or any(x != 0.0 for x in worst.values()) or not cells_equal:
        sys.exit('FATAL: the reproduction run is not bitwise identical to Step 15b: max|dB|=%g, %s, cells_equal=%s'
                 % (dB, worst, cells_equal))
    repro = dict(reference=ref, max_abs_dB=dB, max_abs_other=worst, real_and_predicted_cells_identical=True)
    print('[step24] reproduction: bitwise identical to Step 15b (max|dB| = 0, true/C/A = 0, real and predicted cells identical)')
sha = lambda q: hashlib.sha256(open(q, 'rb').read()).hexdigest()
side = json.load(open(e['SIDE'])); tr = json.load(open(e['PROV_TR']))
rec = dict(status='completed', tag=tag, task=int(e['SLURM_ARRAY_TASK_ID']), slurm_array_job=e['SLURM_ARRAY_JOB_ID'],
           split=e['SPLIT'], arm=e['ARM'], s24_mode=e['S24_MODE'], seed=int(e['SEED']),
           checkpoint_arm='recipe', encoder_arm=e['EARM'], use_adaln=(e['ADALN'] == 'True'),
           fm_source=e['FM'], cond_drop=float(e['CDROP']), drug_encoding='fingerprint', n_params=side['n_params'],
           sampler='euler_ode', nfe=int(e['NFE']), guidance_w=None, guide_t_min=0.0, max_cells_per_cond=200,
           n_conditions=n, cells_min=min(nc), cells_max=max(nc), expect_conditions=expect_n,
           permutation=(e['PERM'] if e['S24_MODE'] == 'shuf' else None), permutation_sha256=perm_sha,
           reproduction=repro,
           prereg=e['PREREG'], commit=e['COMMIT'], training_commit=side.get('commit'), training_provenance=e['PROV_TR'],
           checkpoint=e['CKPT'], checkpoint_sha256=tr['checkpoint_sha256'],
           vectors_npz=v, vectors_sha256=sha(v), per_cell_npz=pc, per_cell_sha256=sha(pc),
           leakage_json=js, leakage_sha256=sha(js),
           data_record=e['RECORD'], data_record_sha256=sha(e['RECORD']),
           harness_step24_sha256=sha('leakage_test_fm_step24.py'), harness_fm_sha256=sha('leakage_test_fm_tahoe.py'),
           harness_base_sha256=sha('leakage_test_base_tahoe.py'), fm_src_sha256=sha('leakage_test_fm_sciplex.py'),
           harness_src_sha256=sha('leakage_test_base_sciplex_array.py'), sampler_sha256=sha('sample_squidiff.py'),
           flow_matching_sha256=sha('Squidiff/flow_matching.py'),
           node=subprocess.run('hostname', shell=True, capture_output=True, text=True).stdout.strip(),
           completed_at=datetime.datetime.now(datetime.timezone.utc).isoformat())
json.dump(rec, open(e['PROV'], 'w'), indent=2)
print('[post] %s: %d conditions (record %d), cells %d-%d, finite, non-negative, mode %s'
      % (tag, n, expect_n, min(nc), max(nc), e['S24_MODE']))
PY
echo "[$(date)] $TAG DONE"
