#!/usr/bin/env python3
"""
port_harness_base_step25.py - generates leakage_test_base_step25.py from the Step 15b Tahoe BASE harness.

Purpose
-------
Step 25 asks whether the BASE model's compound discrimination (PDS 0.6415 / 0.6444 / 0.6549 in Step 15c) requires
the right compound, the question Step 24 answered for the rewired recipe. The base model is evaluated through
leakage_test_base_tahoe.py, which imports `Drug_dose_encoder` itself (its line 30) and calls it inside the
per-condition loop (its line 121). The flow-matching harness of Step 24 strips that import and shadows it; a base-arm
run executes the base harness directly, so the same substitution has to be inserted here.
PREREG_step25_swap_confirmation.md section 2.

As in Steps 15, 16, 18 and 24, the harness is not edited in place: this script writes a new file whose header names
its source and that source's sha256, which the launcher re-checks before every run.

Logic
-----
1. Reads leakage_test_base_tahoe.py, confirms it is the file generated by port_harness_step15.py, and records its
   sha256.
2. Replaces exactly one line - the `from Squidiff.scrna_datasets import Drug_dose_encoder` import - with a block
   that imports the same function privately and defines a substituting wrapper in its place:
     off (default) : calls the real encoder with the arguments it was given, unchanged
     shuf          : every SMILES in the first positional argument is replaced by the SMILES of the structure the
                     committed derangement pairs it with, then encoded as usual, so dose scaling is applied to the
                     substituted fingerprint exactly as to the real one
     zero          : the fingerprint is zeroed after encoding, by the same expression Step 24 uses
   Every other argument is passed through untouched, so the wrapper is signature-agnostic: the harness calls it as
   Drug_dose_encoder([smi]*n, [dose]*n, comb_num=1) and would keep working if that call ever changed.
3. The permutation is loaded on FIRST CALL, not at import: the base harness reads its split from sys.argv at its
   line 186, long after the import at line 30, so no split is known at import time. On first call the block requires
   the environment variable S25_SPLIT, re-checks the permutation record against its own sha256 and against that
   split, and asserts that the harness's own `split` global agrees - a structural check that fails loudly if the
   harness is ever reorganised.
4. The same environment variables as Step 24 (S24_MODE, S24_PERMUTATION) drive both harnesses, so one launcher
   exports one set of variables for recipe and base arms alike and the two arms are constructed identically.
5. Writes leakage_test_base_step25.py, then verifies structurally that nothing else changed: removing the inserted
   block and the generated header from the output restores the source file byte for byte.
Nothing else in the harness, the sampler or the Squidiff package is touched.

Run from the worktree root (CPU, seconds):
    python port_harness_base_step25.py
    python port_harness_base_step25.py --force      # regenerate over an existing file
"""
import argparse
import hashlib
import os
import sys

SRC = "leakage_test_base_tahoe.py"
DST = "leakage_test_base_step25.py"
HEADER = "# GENERATED by port_harness_base_step25.py from %s (sha256 %s) -- do not edit; re-run the port script.\n"

ANCHOR = "from Squidiff.scrna_datasets import Drug_dose_encoder\n"

BLOCK = '''# ---------------------------------------------------------------- Step 25: compound substitution, base harness
# PREREG_step25_swap_confirmation.md section 2. Replaces the harness's own encoder import (its line 30) with the
# same substitution Step 24 applies to the flow-matching harness, so the base and recipe arms are built identically.
# The wrapper substitutes only the first positional argument (the SMILES list) and passes everything else through.
#   S24_MODE unset or 'off' : calls the real encoder unchanged - the harness behaves exactly as in Step 15b
#   S24_MODE=shuf           : each held-out structure receives another held-out structure's SMILES, under the
#                             committed derangement for S25_SPLIT (sha256 re-checked on first call)
#   S24_MODE=zero           : the fingerprint is all zeros (no compound and, since dose enters only as the
#                             fingerprint's log10(dose + 1) scaling, no dose either)
# The permutation loads on FIRST CALL, not here: this harness reads its split from sys.argv further down the file.
import atexit as _s25_atexit, hashlib as _s25_hl, json as _s25_js, os as _s25_os
from Squidiff.scrna_datasets import Drug_dose_encoder as _s25_real

S25_MODE = _s25_os.environ.get('S24_MODE', 'off') or 'off'
if S25_MODE not in ('off', 'shuf', 'zero'):
    sys.exit('FATAL: S24_MODE must be off, shuf or zero, got %r' % S25_MODE)
_S25_MAP, _S25_SEEN, _S25_CALLS, _S25_READY = {}, set(), [0], [False]
if S25_MODE != 'off':
    # every substituting run reports how often the encoder went through this wrapper, so a run in which it was
    # bypassed (and the model saw real fingerprints) cannot pass the launcher's post-check
    _s25_atexit.register(lambda: print('[step25] encoder calls through the substituting wrapper: %d' % _S25_CALLS[0]))
    print('[step25] mode=%s  (permutation loads on the first encoder call)' % S25_MODE)
else:
    print('[step25] mode=off  (the encoder is called with its own arguments, unchanged)')


def _s25_load():
    """Load and check the permutation on the first encoder call, when the harness's split is known."""
    _s25_file = _s25_os.environ.get('S24_PERMUTATION')
    _s25_want_split = _s25_os.environ.get('S25_SPLIT')
    if not _s25_file or not _s25_want_split:
        sys.exit('FATAL: S24_MODE=shuf requires S24_PERMUTATION and S25_SPLIT')
    _s25_p = _s25_js.load(open(_s25_file))
    _s25_sids = _s25_p['structures']
    _s25_sha = _s25_hl.sha256('\\n'.join('%s>%s' % (k, _s25_p['map'][k]) for k in _s25_sids).encode()).hexdigest()
    if _s25_sha != _s25_p['sha256']:
        sys.exit('FATAL: %s does not match its own recorded sha256' % _s25_file)
    if _s25_p.get('split') != _s25_want_split:
        sys.exit('FATAL: %s is for split %r, this run is %r' % (_s25_file, _s25_p.get('split'), _s25_want_split))
    # structural check: the harness's own split variable must agree with the launcher's
    _s25_own = globals().get('split')
    if _s25_own is None:
        sys.exit('FATAL: the harness defines no `split` at the first encoder call; the harness layout changed and '
                 'this port must be re-checked against it')
    if str(_s25_own) != _s25_want_split:
        sys.exit('FATAL: the harness is running split %r, S25_SPLIT says %r' % (_s25_own, _s25_want_split))
    for _s25_s in _s25_sids:
        _s25_a = _s25_p['smiles'][_s25_s]['own']
        _s25_b = _s25_p['smiles'][_s25_s]['substituted']
        if _s25_a == _s25_b:
            sys.exit('FATAL: structure %s would keep its own SMILES' % _s25_s)
        if _S25_MAP.setdefault(_s25_a, _s25_b) != _s25_b:
            sys.exit('FATAL: the SMILES of structure %s is mapped two ways' % _s25_s)
    print('[step25] mode=shuf  %d structures substituted  permutation sha256 %s  split %s'
          % (len(_S25_MAP), _s25_p['sha256'][:12], _s25_want_split))
    _s25_atexit.register(lambda: print('[step25] distinct SMILES substituted during the run: %d of %d'
                                       % (len(_S25_SEEN), len(_S25_MAP))))
    _S25_READY[0] = True


def Drug_dose_encoder(drug_SMILES_list, *_s25_a, **_s25_k):
    """The harness's encoder, with the Step 25 substitution. Only the SMILES list is touched."""
    _S25_CALLS[0] += 1
    if S25_MODE == 'shuf':
        if not _S25_READY[0]:
            _s25_load()
        _s25_out = []
        for _s25_smi in drug_SMILES_list:
            if _s25_smi not in _S25_MAP:
                sys.exit('FATAL: a SMILES reached the encoder that is not in the Step 25 permutation: %s'
                         % str(_s25_smi)[:80])
            _S25_SEEN.add(_s25_smi)
            _s25_out.append(_S25_MAP[_s25_smi])
        drug_SMILES_list = _s25_out
    _s25_fp = _s25_real(drug_SMILES_list, *_s25_a, **_s25_k)
    if S25_MODE == 'zero':
        _s25_fp = np.zeros_like(np.asarray(_s25_fp, dtype=float))
    return _s25_fp
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=SRC)
    ap.add_argument("--dst", default=DST)
    ap.add_argument("--force", action="store_true", help="regenerate over an existing output")
    a = ap.parse_args()
    if os.path.exists(a.dst) and not a.force:
        sys.exit("FATAL: %s exists (use --force to regenerate)" % a.dst)
    src = open(a.src).read()
    if "GENERATED by port_harness_step15.py" not in src[:400]:
        sys.exit("FATAL: %s is not the harness generated by port_harness_step15.py" % a.src)
    if src.count(ANCHOR) != 1:
        sys.exit("FATAL: the encoder import was found %d times in %s (expected once)" % (src.count(ANCHOR), a.src))
    # the inserted block relies on names the harness already imports at module level
    for need in ("import sys", "import numpy as np"):
        if need not in src:
            sys.exit("FATAL: %s does not contain %r, which the inserted block relies on" % (a.src, need))
    if src.index(ANCHOR) < src.index("import sys"):
        sys.exit("FATAL: the encoder import precedes `import sys` in %s; the block cannot be inserted there" % a.src)
    digest = hashlib.sha256(open(a.src, "rb").read()).hexdigest()
    head = HEADER % (a.src, digest)
    out = head + src.replace(ANCHOR, BLOCK)
    open(a.dst, "w").write(out)

    # structural check: removing the header and the inserted block must restore the source exactly
    back = open(a.dst).read()
    if not back.startswith(head):
        sys.exit("FATAL: the generated file does not start with its header")
    back = back[len(head):]
    if back.count(BLOCK) != 1:
        sys.exit("FATAL: the inserted block is not present exactly once in the output")
    if back.replace(BLOCK, ANCHOR) != src:
        sys.exit("FATAL: the generated file differs from the source outside the inserted block")
    print("[port] %s -> %s" % (a.src, a.dst))
    print("[port] source sha256 %s" % digest)
    print("[port] one import replaced; the rest of the file is byte-identical to the source")
    print("[port] generated sha256 %s" % hashlib.sha256(open(a.dst, "rb").read()).hexdigest())


if __name__ == "__main__":
    main()
