#!/bin/bash
#SBATCH --job-name=s20_eval
#SBATCH --partition=condo
#SBATCH -q a2s2
#SBATCH --gres=gpu:h100:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=48G
#SBATCH --time=08:00:00
#SBATCH --array=0-8
#SBATCH --output=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s20ev_%A_%a.out
#SBATCH --error=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s20ev_%A_%a.err
# Step 20 evaluation under PREREG_step20_pairing_sweep.md section 3. The Step 18 evaluation launcher (as patched in commit
# eb23315: per-condition reads hoisted out of the loops) with the minibatch arms in place of ot_pair and no recipe
# re-evaluations (the recipe and ot_pair arrays of Step 18 are the comparators and are not re-run).
#   development (default, STAGE=dev): 9 tasks on drug_split_1.  task T:  m = (4, 8, 32)[T / 3];  seed = T % 3
#       sbatch --array=0-8%2 eval_step20_tahoe.sh
#   confirmation (STAGE=confirm, M=<selected m>): 6 tasks.  task T:  split = (drug_split_0, drug_split_2)[T / 3];  seed = T % 3
#       sbatch --array=0-5%2 --export=ALL,STAGE=confirm,M=<m> eval_step20_tahoe.sh
#     refused unless the committed development record selected exactly this m.
# Tags s20_<split>_mb<m>_seed_<k>; provenance s20ev_<tag>. Every run: leakage_test_fm_step18.py <split> <ckpt> <tag>
# fm_gaussian 50 euler, unguided, per-cell storage on (with the conditioning control cells), MAX_CELLS_PER_COND=200 -
# the Step 18 procedure.
# DRYRUN=1 SLURM_ARRAY_TASK_ID=<T> [STAGE=confirm M=<m>] bash eval_step20_tahoe.sh  runs the guards and stops.
set -eo pipefail
module load cuda/12.2.0
source /share/apps/NYUAD5/miniconda/3-4.11.0/etc/profile.d/conda.sh
conda activate /scratch/ni2071/conda_envs/squidiff
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export SQUIDIFF_SAVE_PER_CELL=1
export S12_GUIDE_TMIN=0.0
unset S12_GUIDANCE_W SQUIDIFF_DRUG_ENCODING
W=${S20_W:-/scratch/ni2071/Diffusion/Squidiff_git/Squidiff}      # S20_W override for synthetic tests only
cd "$W"
NFE=50; PREREG=PREREG_step20_pairing_sweep.md; RECORD=tahoe_results/step15_data_record.json
MBREC=tahoe_results/minibatch_pairing_check.json; DEVREC=tahoe_results/step20_analysis_development.json

T=$SLURM_ARRAY_TASK_ID
case "$T" in *[!0-9]*|"") echo "FATAL: non-numeric task id: $T"; exit 1 ;; esac
STAGE=${STAGE:-dev}

# --- decode the task (as train_step20_tahoe.sh and finalize_step20.py) ---
if [ "$STAGE" = "dev" ]; then
  if [ -n "${M:-}" ]; then echo "FATAL: M is set ($M) but STAGE=dev; the development stage takes m from the task index"; exit 1; fi
  if [ "$T" -gt 8 ]; then echo "FATAL: development task out of range (0-8): $T"; exit 1; fi
  MS=(4 8 32); M=${MS[$(( T / 3 ))]}; SEED=$(( T % 3 )); SPLIT_IDX=1
elif [ "$STAGE" = "confirm" ]; then
  case "${M:-}" in 4|8|32) ;; *) echo "FATAL: STAGE=confirm needs M = 4, 8 or 32, got '${M:-}'"; exit 1 ;; esac
  if [ "$T" -gt 5 ]; then echo "FATAL: confirmation task out of range (0-5): $T"; exit 1; fi
  SI=(0 2); SPLIT_IDX=${SI[$(( T / 3 ))]}; SEED=$(( T % 3 ))
else
  echo "FATAL: STAGE must be dev or confirm, got '$STAGE'"; exit 1
fi
SPLIT=drug_split_${SPLIT_IDX}
ARM=mb${M}
PIN=tahoe_results/minibatch_pairing_written_${SPLIT}_m${M}.json

# --- pre-registration, scripts (launchers, finaliser, scorer, plot - prereg section 9 and its dated note), harness and
#     sampler sources, records and this task's pin committed and clean ---
N=$(grep -c '^## ' $PREREG)
if [ "$N" -lt 9 ]; then echo "FATAL: prereg has $N sections, expected at least 9"; exit 1; fi
TRACKED="$PREREG port_harness_step18.py leakage_test_fm_step18.py port_harness_step15.py leakage_test_base_tahoe.py leakage_test_fm_tahoe.py"
TRACKED="$TRACKED eval_step20_tahoe.sh train_step20_tahoe.sh finalize_step20.py score_step20_tahoe.py plot_step20.py check_minibatch_pairing_tahoe.py $RECORD $MBREC $PIN"
if [ "$STAGE" = "confirm" ]; then TRACKED="$TRACKED $DEVREC"; fi
for f in $TRACKED; do git ls-files --error-unmatch $f >/dev/null 2>&1 || { echo "FATAL: $f not committed (PREREG section 9)"; exit 1; }; done
git diff --quiet -- $TRACKED leakage_test_base_sciplex_array.py leakage_test_fm_sciplex.py sample_squidiff.py train_squidiff.py Squidiff \
  || { echo "FATAL: prereg, harness, scripts, sampler or encoder sources uncommitted"; exit 1; }
[ -s "$RECORD" ] || { echo "FATAL: missing data record $RECORD"; exit 1; }
python - <<'PY'
import hashlib, re, sys
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
for gen, src, dst in (('port_harness_step15.py', 'leakage_test_base_sciplex_array.py', 'leakage_test_base_tahoe.py'),
                      ('port_harness_step15.py', 'leakage_test_fm_sciplex.py', 'leakage_test_fm_tahoe.py'),
                      ('port_harness_step18.py', 'leakage_test_fm_tahoe.py', 'leakage_test_fm_step18.py')):
    head = open(dst).read(400)
    m = re.search(r'GENERATED by %s from (\S+) \(sha256 ([0-9a-f]{64})\)' % re.escape(gen), head)
    if not m or m.group(1) != src: sys.exit('FATAL: %s lacks a valid generated header from %s' % (dst, gen))
    if m.group(2) != sha(src): sys.exit('FATAL: %s is stale: %s changed since the port' % (dst, src))
if "_PC.setdefault('ctrl', [])" not in open('leakage_test_fm_step18.py').read(): sys.exit('FATAL: leakage_test_fm_step18.py lacks the ctrl storage')
print('[port] generated harness files are current; ctrl storage present')
PY
COMMIT=$(git rev-parse HEAD)

CKPT=$W/step20/${ARM}/${SPLIT}_seed_${SEED}/model_0.9999.pt
PROV_TR=$W/provenance/s20tr_${SPLIT}_${ARM}_seed_${SEED}.json
TAG=s20_${SPLIT}_${ARM}_seed_${SEED}
PROV=$W/provenance/s20ev_${TAG}.json
SIDE=${CKPT}.encoding.json
export STAGE M ARM SPLIT SEED SPLIT_IDX CKPT SIDE PROV_TR TAG PROV RECORD MBREC DEVREC PIN NFE PREREG COMMIT
for f in "$CKPT" "$PROV_TR" "$SIDE"; do [ -s "$f" ] || { echo "FATAL: missing $f"; exit 1; }; done
for f in tahoe_results/vectors_${TAG}.npz tahoe_results/vectors_${TAG}_pc.npz tahoe_results/leakage_${TAG}.json "$PROV"; do
  [ -e "$f" ] && { echo "FATAL: output exists: $f"; exit 1; }
done
EXPECT_N=$(python -c "import json; print(json.load(open('$RECORD'))['splits']['$SPLIT_IDX']['n_test_conditions'])")
export EXPECT_N
if [ "$STAGE" = "confirm" ]; then PORT_OFF=100; else PORT_OFF=0; fi
export MASTER_PORT=$(( 25000 + PORT_OFF + T ))

# --- the checkpoint is the certified one; the sidecar and the minibatch control pin match the task; confirmation locked ---
python - <<'PY'
import hashlib, json, os, sys
e = os.environ
if e['STAGE'] == 'confirm':
    dev = json.load(open(e['DEVREC']))
    sel = dev.get('selection', {})
    if dev.get('final') is not False or sel.get('split') != 'drug_split_1':
        sys.exit('FATAL: %s is not the development record' % e['DEVREC'])
    if sel.get('selected_m') is None or int(sel['selected_m']) != int(e['M']):
        sys.exit('FATAL: the development stage selected m = %s (%s), not m = %s' % (sel.get('selected_m'), sel.get('verdict'), e['M']))
p = json.load(open(e['PROV_TR']))
if p.get('status') != 'completed' or p.get('split') != e['SPLIT'] or int(p.get('seed', -1)) != int(e['SEED']) or p.get('arm') != e['ARM'] or int(p.get('m', -1)) != int(e['M']):
    sys.exit('FATAL: training provenance %s is not a completed record for arm %s split %s seed %s' % (e['PROV_TR'], e['ARM'], e['SPLIT'], e['SEED']))
h = hashlib.sha256()
with open(e['CKPT'], 'rb') as f:
    for c in iter(lambda: f.read(1 << 24), b''): h.update(c)
if h.hexdigest() != p.get('checkpoint_sha256'): sys.exit('FATAL: checkpoint sha256 differs from the certified one in %s' % e['PROV_TR'])
s = json.load(open(e['SIDE']))
want = dict(arm=e['ARM'], m=int(e['M']), split=e['SPLIT'], seed=int(e['SEED']), encoder_arm='mlp', use_adaln=True, fm_source='gaussian',
            cond_drop=0.0, drug_encoding='fingerprint', drug_dimension=1024, memory_size=0)
for k, v in want.items():
    if s.get(k) != v: sys.exit('FATAL: sidecar %s=%r, task expects %r' % (k, s.get(k), v))
pin = json.load(open(e['PIN']))
if p.get('control_mb_sha256') != pin['sha256']: sys.exit('FATAL: the run\'s minibatch control pin differs from %s' % e['PIN'])
print('[sidecar] %s split=%s seed=%s n_params=%s trained_at=%s | minibatch control pin %s'
      % (s['arm'], s['split'], s['seed'], s['n_params'], str(s.get('commit'))[:7], p['control_mb_sha256'][:12]))
PY

echo "[prereg] $N sections committed | [commit] $COMMIT | [node] $(hostname)"
echo "[task] T=$T  $TAG  stage=$STAGE  arm=$ARM  m=$M  split=$SPLIT  seed=$SEED  expect_conditions=$EXPECT_N  guidance=none  nfe=$NFE"
if [ "${DRYRUN:-0}" = "1" ]; then echo "[dryrun] guards passed for $TAG; nothing run"; exit 0; fi
python -u leakage_test_fm_step18.py "$SPLIT" "$CKPT" "$TAG" fm_gaussian "$NFE" euler

# --- post: outputs complete and consistent; ctrl stored; provenance (verbatim from the patched Step 18 launcher) ---
python - <<'PY'
import datetime, hashlib, json, os, re, subprocess, sys
import numpy as np
e = os.environ
tag = e['TAG']; expect_n = int(e['EXPECT_N'])
v = 'tahoe_results/vectors_%s.npz' % tag; pc = 'tahoe_results/vectors_%s_pc.npz' % tag; js = 'tahoe_results/leakage_%s.json' % tag
for f in (v, pc, js):
    if not os.path.isfile(f) or os.path.getsize(f) == 0: sys.exit('FATAL: missing or empty ' + f)
d = np.load(v, allow_pickle=True)
n = len(d['cond'])
if n != expect_n: sys.exit('FATAL: %d conditions, data record expects %d for %s' % (n, expect_n, e['SPLIT']))
if len(set(map(str, d['cond']))) != n: sys.exit('FATAL: duplicate condition labels')
for k in ('true', 'A', 'B', 'C'):
    if not np.all(np.isfinite(d[k])): sys.exit('FATAL: non-finite %s' % k)
if float(np.asarray(d['B']).min()) < 0: sys.exit('FATAL: negative predicted expression')
p = np.load(pc, allow_pickle=True)
if 'ctrl' not in p.files: sys.exit('FATAL: the per-cell file has no ctrl key')
pc_pred = p['pred']; pc_ctrl = p['ctrl']  # read each archive member ONCE (the eb23315 fix: p[k][i] in a loop re-reads the member)
if len(pc_pred) != expect_n or len(pc_ctrl) != expect_n: sys.exit('FATAL: per-cell file has %d / %d conditions' % (len(pc_pred), len(pc_ctrl)))
nc = [int(np.asarray(a).shape[0]) for a in pc_pred]
if max(nc) > 200: sys.exit('FATAL: per-cell population larger than the 200-cell cap: %d' % max(nc))
for i in range(expect_n):
    if np.asarray(pc_ctrl[i]).shape != np.asarray(pc_pred[i]).shape: sys.exit('FATAL: ctrl and pred shapes differ in condition %d' % i)
    if not np.all(np.isfinite(np.asarray(pc_ctrl[i], np.float32))): sys.exit('FATAL: non-finite ctrl in condition %d' % i)
log = open('logger_files/s20ev_%s_%s.out' % (e['SLURM_ARRAY_JOB_ID'], e['SLURM_ARRAY_TASK_ID'])).read()
m = re.search(r'encoder arm detected from checkpoint: (\S+) \(memory_size=(\d+)\)', log)
if not m or m.group(1) != 'mlp' or int(m.group(2)) != 0: sys.exit('FATAL: sampler detected arm %r, task expects mlp 0' % (m.group(0) if m else None))
a = re.search(r'checkpoint architecture: (\S+)', log)
if not a or a.group(1) != 'adaLN-Zero': sys.exit('FATAL: sampler architecture %r, task expects adaLN-Zero' % (a.group(1) if a else None))
de = re.search(r'drug encoding detected from checkpoint: (\S+) \(drug_dimension=(\d+)\)', log)
if not de or de.group(1) != 'fingerprint' or int(de.group(2)) != 1024: sys.exit('FATAL: sampler drug encoding %r, task expects fingerprint (1024)' % (de.group(0) if de else None))
he = re.search(r'\[harness\] drug encoder = (\S+) \(drug_dimension=(\d+)\)', log)
if not he or he.group(1) != 'fingerprint' or int(he.group(2)) != 1024: sys.exit('FATAL: harness drug encoder %r, task expects fingerprint (1024)' % (he.group(0) if he else None))
if '[step18] harness stores the conditioning control cells' not in log: sys.exit('FATAL: the Step 18 harness did not print its ctrl line')
g = re.search(r'\[step12\] guidance_w=(\S+)', log)
if not g or g.group(1) != 'None': sys.exit('FATAL: guidance_w=%s for an unguided arm' % (g.group(1) if g else None))
sha = lambda q: hashlib.sha256(open(q, 'rb').read()).hexdigest()
tr = json.load(open(e['PROV_TR']))
rec = dict(status='completed', tag=tag, kind='mb', stage=e['STAGE'], task=int(e['SLURM_ARRAY_TASK_ID']), slurm_array_job=e['SLURM_ARRAY_JOB_ID'],
           split=e['SPLIT'], arm=e['ARM'], m=int(e['M']), seed=int(e['SEED']), encoder_arm='mlp', use_adaln=True, fm_source='gaussian', cond_drop=0.0,
           drug_encoding='fingerprint', drug_dimension=1024, sampler='euler_ode', nfe=int(e['NFE']), guidance_w=None, guide_t_min=0.0, max_cells_per_cond=200,
           n_conditions=n, cells_min=min(nc), cells_max=max(nc), expect_conditions=expect_n, ctrl_stored=True,
           prereg=e['PREREG'], commit=e['COMMIT'], training_commit=tr.get('commit'), training_provenance=e['PROV_TR'],
           checkpoint=e['CKPT'], checkpoint_sha256=tr['checkpoint_sha256'], control_mb_sha256=tr.get('control_mb_sha256'),
           vectors_npz=v, vectors_sha256=sha(v), per_cell_npz=pc, per_cell_sha256=sha(pc), leakage_json=js, leakage_sha256=sha(js),
           data_record=e['RECORD'], data_record_sha256=sha(e['RECORD']), measure_record=e['MBREC'], measure_record_sha256=sha(e['MBREC']),
           pin=e['PIN'], pin_sha256=sha(e['PIN']),
           harness_sha256=sha('leakage_test_fm_step18.py'), harness_src_sha256=sha('leakage_test_fm_tahoe.py'), harness_base_sha256=sha('leakage_test_base_tahoe.py'),
           sampler_sha256=sha('sample_squidiff.py'), datasets_sha256=sha('Squidiff/scrna_datasets.py'), flow_matching_sha256=sha('Squidiff/flow_matching.py'),
           node=subprocess.run('hostname', shell=True, capture_output=True, text=True).stdout.strip(),
           completed_at=datetime.datetime.now(datetime.timezone.utc).isoformat())
json.dump(rec, open(e['PROV'], 'w'), indent=2)
print('[post] %s: %d conditions (record %d), cells %d-%d, finite, non-negative, ctrl stored, fingerprint bound by sampler and harness, unguided' % (tag, n, expect_n, min(nc), max(nc)))
PY
echo "[$(date)] $TAG DONE"
