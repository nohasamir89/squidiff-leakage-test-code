#!/usr/bin/env python
"""port_harness_step15.py -- generate the Tahoe evaluation harness from the frozen sci-Plex harness.

PREREG_step15b_tahoe_model.md section 9: "eval_step15_tahoe.sh driving the Step 13 harness ported to the Tahoe file prefix
and line list, per-cell storage on". The port is done by exact-string replacement so that everything except the data
source, the paired-control definition and the output directory stays byte-identical to the sci-Plex evaluator:

  leakage_test_base_sciplex_array.py  ->  leakage_test_base_tahoe.py
    1. DATA_DIR and the test-file prefix (sci_plex_test_* -> tahoe_test_*, datasets_step15)
    2. paired control = vehicle cells of the same cell line AND plate (PREREG_step15a 4.8). The plate is the last field
       of `Group` (<cell_name>_<drug>_<dose/10000>_p<plate>, drug names carry no underscore), present in both files;
       the control pool is keyed by (line, plate) and Protocols B and C draw from it as before.
    3. output directory leakage_results/ -> tahoe_results/
  leakage_test_fm_sciplex.py  ->  leakage_test_fm_tahoe.py
    4. the wrapper executes the ported base file instead of the sci-Plex one (its encoder anchors are unchanged)

Every anchor must occur exactly once in the source, otherwise the script aborts and writes nothing. The generated files
carry a header with the source file name and sha256; run this script again after any change to the sources.
Usage:  python port_harness_step15.py            (from the repository root; prints a unified diff per file)
"""
import difflib
import hashlib
import os
import sys

BASE_SRC, BASE_DST = 'leakage_test_base_sciplex_array.py', 'leakage_test_base_tahoe.py'
FM_SRC, FM_DST = 'leakage_test_fm_sciplex.py', 'leakage_test_fm_tahoe.py'

BASE_EDITS = [
    # 1. data source
    ("DATA_DIR = '/scratch/ni2071/Diffusion/sciplex/datasets_corrected'",
     "DATA_DIR = '/scratch/ni2071/Diffusion/tahoe/datasets_step15'   # Step 15 port: Tahoe test files"),
    ("treated = sc.read_h5ad(f'{DATA_DIR}/sci_plex_test_{split}.h5ad')",
     "treated = sc.read_h5ad(f'{DATA_DIR}/tahoe_test_{split}.h5ad')"),
    ("control = sc.read_h5ad(f'{DATA_DIR}/sci_plex_test_{split}_control.h5ad')",
     "control = sc.read_h5ad(f'{DATA_DIR}/tahoe_test_{split}_control.h5ad')"),
    # 2. plate per row, from the Group suffix, in both files
    ("    c_line = control.obs['cell_name'].astype(str).values\n",
     "    c_line = control.obs['cell_name'].astype(str).values\n"
     "    # Step 15 port: the paired control is the vehicle population of the same line AND plate (PREREG_step15a 4.8).\n"
     "    # Group ends with _p<plate> in both files (drug names carry no underscore), so the plate is its last field.\n"
     "    def _plate(groups):\n"
     "        p = np.array([g.rsplit('_p', 1)[1] for g in groups])\n"
     "        if not all(x.isdigit() for x in p):\n"
     "            raise SystemExit('FATAL: non-numeric plate suffix in Group')\n"
     "        return p\n"
     "    t_plate = _plate(t_group)\n"
     "    c_plate = _plate(control.obs['Group'].astype(str).values)\n"),
    ("    ctrl_pool = {L: cX[c_line == L] for L in np.unique(c_line)}",
     "    ctrl_pool = {(L, P): cX[(c_line == L) & (c_plate == P)]\n"
     "                 for L in np.unique(c_line) for P in np.unique(c_plate[c_line == L])}   # Step 15 port: (line, plate)"),
    ("        line = t_line[m][0]\n        pool = ctrl_pool.get(line)\n",
     "        line = t_line[m][0]\n        plate = t_plate[m][0]\n        pool = ctrl_pool.get((line, plate))   # Step 15 port\n"),
    # 3. output directory (records for Tahoe live in tahoe_results/, never leakage_results/)
    ("OUTDIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'leakage_results')",
     "OUTDIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tahoe_results')   # Step 15 port"),
]

FM_EDITS = [
    ("sys.argv = ['leakage_test_base_sciplex_array.py', SPLIT, CKPT, TAG]",
     "sys.argv = ['leakage_test_base_tahoe.py', SPLIT, CKPT, TAG]   # Step 15 port"),
    ("_src = open('leakage_test_base_sciplex_array.py').read()",
     "_src = open('leakage_test_base_tahoe.py').read()   # Step 15 port: the ported base harness"),
]


def sha256(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def port(src, dst, edits):
    text = open(src).read()
    for old, new in edits:
        n = text.count(old)
        if n != 1:
            sys.exit('FATAL: anchor found %d times in %s (expected 1):\n%s' % (n, src, old))
        text = text.replace(old, new)
    header = ('# GENERATED by port_harness_step15.py from %s (sha256 %s) -- do not edit; re-run the port script.\n'
              % (src, sha256(src)))
    # keep a leading shebang first if the source has one
    if text.startswith('#!'):
        first, rest = text.split('\n', 1)
        out = first + '\n' + header + rest
    else:
        out = header + text
    open(dst, 'w').write(out)
    diff = difflib.unified_diff(open(src).read().splitlines(), out.splitlines(), src, dst, lineterm='', n=1)
    print('\n'.join(diff))
    print('[port] wrote %s (%d lines, sha256 %s)\n' % (dst, out.count('\n'), sha256(dst)))


if __name__ == '__main__':
    for f in (BASE_SRC, FM_SRC):
        if not os.path.isfile(f):
            sys.exit('FATAL: run from the repository root; missing %s' % f)
    port(BASE_SRC, BASE_DST, BASE_EDITS)
    port(FM_SRC, FM_DST, FM_EDITS)
