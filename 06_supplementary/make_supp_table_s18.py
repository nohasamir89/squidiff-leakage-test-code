    (R_ANY, 'secondary_any_set_hit_recipe_minus_mean_response_group', GROUP, 'any_set_hit', 'recipe', 'mean_response'),
    (C_REW_BLIND, 'secondary_rawhit_Q2_recipe_minus_mean_response_cell', CELL, 'hit', 'recipe', 'mean_response'),
