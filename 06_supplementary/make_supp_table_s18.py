#!/usr/bin/env python3
"""
make_supp_table_s18.py - Supplementary Table S18: recognition by RNA fingerprinting on Tahoe-100M
(Supplementary Note 6; Supplementary Fig. S3).

Purpose
-------
Supplementary Note 6 asks an external, published method (RNA fingerprinting) to recognise the compound in a
population of cells. One fingerprint per held-out compound is learned from half of the measured cells; the other
half, the populations generated by the models and the references are then queried. The note cites this table for
every number, and the caption of Supplementary Fig. S3 cites it for the values of the figure and for the queries
of single cells. All numbers come from one committed record. This script lays them out in one table, so that each
number traces to the record and is rounded once.

The quantities (as defined before the data were scored):
    recognised          the true structure is in the top credible set of the query with a positive sign;
                        a query that receives no credible set counts as not recognised
    chance              the number of structures in the top credible set with a positive sign, divided by the
                        number of structures that have a fingerprint: what a random guess of that size would hit
    recognised - chance the measure used for every comparison (a query answered with many structures is not
                        credited for holding the true one among them)
    no compound         the query received no credible set
All four are averaged over the conditions whose structure kept a fingerprint, and for a model over three seeds.

Four parts:
  a  whole populations (one query per condition): the four quantities for the eight sets queried
     (the values of Supplementary Fig. S3);
  b  single cells (the first ten cells of each query population): the same for the six sets queried;
  c  the comparisons on recognised - chance, with intervals;
  d  the same comparisons on the recognition rate without the correction for chance, and the comparison of the
     rewired model with the compound-blind average under two other rules of recognition.
Every comparison was named before the data were scored; none is exploratory.

Logic
-----
- Inputs (committed records only; see supp_table_common.guard):
      tahoe_results/step22_analysis.json     per_split/<s>/rates/<level>/<set>, per_seed, contrasts, coverage, K
      figures/squidiff_publication_figures/fig5_values.csv   the values Supplementary Fig. S3 was drawn from
                                                             (panel d of the old Figure 5); check only
  Record names -> names in the paper: real_half = measured cells (the half not used for the fingerprints);
  recipe = rewired model; ot_pair = rewired model with optimal-transport pairing (exact matching); mb32 = the same
  with minibatch matching (m = 32); mean_response = compound-blind average; control_paste = unaltered vehicle
  cells; ridge_train = training-set ridge; ridge_S7 = cross-validated ridge; group = whole populations; cell =
  single cells; hit = recognised; excess = recognised minus chance; unassigned = no compound assigned.
- Checks, all before anything is written (a failure stops the script):
    1. Record: it is the final record of the three splits; settings; the structures kept and the conditions
       covered agree with each other; for every set and level, recognised minus chance equals the stored
       difference (1e-9); each model value is the mean of its three seeds; the stored outcome of the four
       pre-specified tests follows from their intervals.
    2. Comparisons: the record holds exactly the 31 comparisons laid out here; the value of each equals the
       difference of the two rates it compares (1e-9); the stored word for each interval follows from the interval.
    3. Every value of the figure (48 rows of panel d: recognised, chance and no compound assigned, in per cent)
       equals the value given here (1e-9).
    4. The statements of Supplementary Note 6 hold: the percentages and counts it quotes at their printed
       precision; after correction for chance the rewired model is not recognised more often than the
       compound-blind average or the unaltered vehicle cells, for whole populations and for single cells;
       optimal-transport pairing raises recognition of whole populations on every split (EXPECTED below; checks
       only, never inputs to a computation).
- Units and rounding: the record stores fractions. The table shows per cent (parts a, b) and percentage points
  (parts c, d), two decimals, one for the share with no compound assigned; each value is rounded once from full
  precision. The csv output keeps the fractions of the record.
- Outputs (never overwritten): supplementary_tables/supp_table_S18.csv and .md (see supp_table_common).

Run from the research worktree root (supp_table_common.py must be in the same folder):
    python3 make_supp_table_s18.py
"""
