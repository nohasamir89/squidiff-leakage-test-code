#!/usr/bin/env python
"""port_harness_step18.py -- generate the Step 18 evaluation harness from the Step 15 one (PREREG_step18_tahoe_ot_pairing.md
section 3).

leakage_test_fm_tahoe.py executes the frozen base harness leakage_test_base_tahoe.py from its source text after two
in-memory anchor replacements (the Step 12 guidance routing). Step 18 needs one more output: the Protocol-B control
cells each generated cell was conditioned on (`cfB`, the harness's own RandomState(i_cond) draw over the (line, plate)
vehicle pool), stored per condition in the per-cell file under the key `ctrl`, row-aligned with `pred`. The generated
file leakage_test_fm_step18.py adds two anchor replacements to the base source before it is executed: one appends
cfB to the per-cell store right after the real cells, one adds `ctrl=` to the per-cell savez. No model call, draw or
selection changes, so the mean vectors and the generated cells are those of the Step 15 procedure (asserted on the
recipe re-evaluations by eval_step18_tahoe.sh).

Every anchor must occur exactly once, otherwise nothing is written. The generated file carries a header with the
source name and sha256; eval_step18_tahoe.sh refuses a stale file.
Usage:  python port_harness_step18.py            (from the repository root; prints a unified diff)
"""
import difflib
import hashlib
import os
import sys

FM_SRC, FM_DST = 'leakage_test_fm_tahoe.py', 'leakage_test_fm_step18.py'

FM_EDITS = [
    ("exec(_src)\n",
     "# Step 18 (PREREG_step18_tahoe_ot_pairing.md section 3): store the Protocol-B conditioning control cells per\n"
     "# condition (output only: no model call, draw or selection changes). Each anchor must occur exactly once.\n"
     "for _a, _b in ((\"            _PC['true'].append(np.asarray(real_sub, dtype=np.float32))\\n\",\n"
     "                \"            _PC['true'].append(np.asarray(real_sub, dtype=np.float32))\\n\"\n"
     "                \"            _PC.setdefault('ctrl', []).append(np.asarray(cfB.detach().cpu().numpy(), dtype=np.float32))   # Step 18\\n\"),\n"
     "               (\"                        true=np.array(_PC['true'], dtype=object))\\n\",\n"
     "                \"                        true=np.array(_PC['true'], dtype=object),\\n\"\n"
     "                \"                        ctrl=np.array(_PC['ctrl'], dtype=object))   # Step 18\\n\")):\n"
     "    if _src.count(_a) != 1:\n"
     "        sys.exit('FATAL: Step 18 harness anchor %r found %d times' % (_a, _src.count(_a)))\n"
     "    _src = _src.replace(_a, _b)\n"
     "print('[step18] harness stores the conditioning control cells (ctrl) in the per-cell file')\n"
     "exec(_src)\n"),
]


def sha256(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def port(src, dst, edits):
    text = open(src).read()
    for old, new in edits:
        n = text.count(old)
        if n != 1:
            sys.exit('FATAL: anchor found %d times in %s (expected 1):\n%s' % (n, src, old))
        text = text.replace(old, new)
    header = ('# GENERATED by port_harness_step18.py from %s (sha256 %s) -- do not edit; re-run the port script.\n'
              % (src, sha256(src)))
    out = header + text
    open(dst, 'w').write(out)
    diff = difflib.unified_diff(open(src).read().splitlines(), out.splitlines(), src, dst, lineterm='', n=1)
    print('\n'.join(diff))
    print('[port] wrote %s (%d lines, sha256 %s)\n' % (dst, out.count('\n'), sha256(dst)))


if __name__ == '__main__':
    if not os.path.isfile(FM_SRC):
        sys.exit('FATAL: run from the repository root; missing %s' % FM_SRC)
    port(FM_SRC, FM_DST, FM_EDITS)
