#!/bin/bash
#SBATCH --job-name=s16_eval
#SBATCH --partition=condo
#SBATCH -q a2s2
#SBATCH --gres=gpu:h100:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=48G
#SBATCH --time=08:00:00
#SBATCH --array=0-17
#SBATCH --output=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s16ev_%A_%a.out
#SBATCH --error=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff/logger_files/s16ev_%A_%a.err
# Step 16 evaluation under PREREG_step16_tahoe_targets.md section 9: one task per checkpoint, same decode as training
# (task T -> split = T / 6, arm = (T % 6) / 3 with 0 targets / 1 targets_shuf, seed = T % 3).
#   development first:  sbatch --array=6-11 eval_step16_tahoe.sh      confirmation:  sbatch --array=0-5,12-17 eval_step16_tahoe.sh
# Every run: leakage_test_fm_step16.py <split> <ckpt> <tag> fm_gaussian 50 euler, unguided, per-cell storage on,
# MAX_CELLS_PER_COND=200 - the Step 15b procedure. leakage_test_fm_step16.py is GENERATED from leakage_test_fm_tahoe.py by
# port_harness_step16.py; the only change is how the drug encoder is selected: the arm's encoding is named in
# SQUIDIFF_DRUG_ENCODING (two Step 16 encodings share the checkpoint width 1,569) and asserted against that width by the
# harness and by the patched sampler. DRYRUN=1 SLURM_ARRAY_TASK_ID=<T> bash eval_step16_tahoe.sh runs the guards and stops.
# Post: condition count == data record n_test_conditions; finite, non-negative predictions; the sampler and the harness
# both report the arm's encoding; provenance/s16ev_<TAG>.json with sha256 of every input and output.
set -eo pipefail
module load cuda/12.2.0
source /share/apps/NYUAD5/miniconda/3-4.11.0/etc/profile.d/conda.sh
conda activate /scratch/ni2071/conda_envs/squidiff
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export SQUIDIFF_SAVE_PER_CELL=1
export S12_GUIDE_TMIN=0.0
unset S12_GUIDANCE_W
W=/scratch/ni2071/Diffusion/Squidiff_git/Squidiff
cd "$W"
NFE=50; PREREG=PREREG_step16_tahoe_targets.md; RECORD=tahoe_results/step15_data_record.json; TARGETS=tahoe_results/step15_targets_curated_hgnc.csv

T=$SLURM_ARRAY_TASK_ID
case "$T" in *[!0-9]*|"") echo "FATAL: non-numeric task id: $T"; exit 1 ;; esac
if [ "$T" -gt 17 ]; then echo "FATAL: task out of range (0-17): $T"; exit 1; fi

# --- pre-registration, scripts, harness and sampler sources committed and clean ---
N=$(grep -c '^## ' $PREREG)
if [ "$N" -lt 9 ]; then echo "FATAL: prereg has $N sections, expected at least 9"; exit 1; fi
TRACKED="$PREREG port_harness_step16.py leakage_test_fm_step16.py port_harness_step15.py leakage_test_base_tahoe.py leakage_test_fm_tahoe.py eval_step16_tahoe.sh score_step16_tahoe.py finalize_step16.py patch_step16.py $RECORD $TARGETS"
for f in $TRACKED; do git ls-files --error-unmatch $f >/dev/null 2>&1 || { echo "FATAL: $f not committed (PREREG section 9)"; exit 1; }; done
git diff --quiet -- $TRACKED leakage_test_base_sciplex_array.py leakage_test_fm_sciplex.py sample_squidiff.py train_squidiff.py Squidiff \
  || { echo "FATAL: prereg, harness, scorer, sampler or encoder sources uncommitted"; exit 1; }
[ -s "$RECORD" ] || { echo "FATAL: missing data record $RECORD"; exit 1; }
# the generated harness files must be current: their headers name the source sha256
python - <<'PY'
import hashlib, re, sys
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
for gen, src, dst in (('port_harness_step15.py', 'leakage_test_base_sciplex_array.py', 'leakage_test_base_tahoe.py'),
                      ('port_harness_step15.py', 'leakage_test_fm_sciplex.py', 'leakage_test_fm_tahoe.py'),
                      ('port_harness_step16.py', 'leakage_test_fm_tahoe.py', 'leakage_test_fm_step16.py')):
    head = open(dst).read(400)
    m = re.search(r'GENERATED by %s from (\S+) \(sha256 ([0-9a-f]{64})\)' % re.escape(gen), head)
    if not m or m.group(1) != src: sys.exit('FATAL: %s lacks a valid generated header from %s' % (dst, gen))
    if m.group(2) != sha(src): sys.exit('FATAL: %s is stale: %s changed since the port' % (dst, src))
if 'SQUIDIFF_DRUG_ENCODING' not in open('leakage_test_fm_step16.py').read(): sys.exit('FATAL: leakage_test_fm_step16.py lacks the encoding override')
if 'SQUIDIFF_DRUG_ENCODING' not in open('sample_squidiff.py').read(): sys.exit('FATAL: sample_squidiff.py is not patched (patch_step16.py)')
print('[port] generated harness files are current; encoding override present in harness and sampler')
PY
COMMIT=$(git rev-parse HEAD)

# --- decode the task (identical to train_step16_tahoe.sh) ---
SPLIT_IDX=$(( T / 6 )); WITHIN=$(( T % 6 )); ARM_IDX=$(( WITHIN / 3 )); SEED=$(( WITHIN % 3 ))
SPLIT=drug_split_${SPLIT_IDX}
case $ARM_IDX in
  0) ARM=targets;      ENC=fp_targets ;;
  1) ARM=targets_shuf; ENC=fp_targets_shuf ;;
  *) echo "FATAL: bad arm index $ARM_IDX"; exit 1 ;;
esac
export ARM SPLIT SEED ENC
export SQUIDIFF_DRUG_ENCODING=$ENC
CKPT=$W/step16/${ARM}/${SPLIT}_seed_${SEED}/model_0.9999.pt
SIDE=${CKPT}.encoding.json
PROV_TR=$W/provenance/s16tr_${SPLIT}_${ARM}_seed_${SEED}.json
TAG=s16_${SPLIT}_${ARM}_seed_${SEED}
PROV=$W/provenance/s16ev_${TAG}.json
export CKPT SIDE PROV_TR TAG PROV RECORD TARGETS SPLIT_IDX NFE PREREG COMMIT
for f in "$CKPT" "$SIDE" "$PROV_TR"; do [ -s "$f" ] || { echo "FATAL: missing $f"; exit 1; }; done
for f in tahoe_results/vectors_${TAG}.npz tahoe_results/vectors_${TAG}_pc.npz tahoe_results/leakage_${TAG}.json "$PROV"; do
  [ -e "$f" ] && { echo "FATAL: output exists: $f"; exit 1; }
done
EXPECT_N=$(python -c "import json; print(json.load(open('$RECORD'))['splits']['$SPLIT_IDX']['n_test_conditions'])")
export EXPECT_N
export MASTER_PORT=$(( 22000 + T ))

# --- sidecar consistent with the task, bound to the certified checkpoint and to the committed encoder inputs ---
python - <<'PY'
import hashlib, json, os, sys
e = os.environ
sha = lambda q: hashlib.sha256(open(q, 'rb').read()).hexdigest()
s = json.load(open(e['SIDE'])); p = json.load(open(e['PROV_TR']))
want = dict(arm=e['ARM'], split=e['SPLIT'], seed=int(e['SEED']), encoder_arm='mlp', use_adaln=True, fm_source='gaussian', cond_drop=0.0,
            drug_encoding=e['ENC'], drug_dimension=1569, memory_size=0)
for k, v in want.items():
    if s.get(k) != v: sys.exit('FATAL: sidecar %s=%r, task expects %r' % (k, s.get(k), v))
if p.get('status') != 'completed' or p.get('tag') != '%s_%s_seed_%s' % (e['SPLIT'], e['ARM'], e['SEED']):
    sys.exit('FATAL: training provenance is not a completed record for this task: %s' % e['PROV_TR'])
h = hashlib.sha256()
with open(e['CKPT'], 'rb') as f:
    for c in iter(lambda: f.read(1 << 24), b''): h.update(c)
if h.hexdigest() != p.get('checkpoint_sha256'): sys.exit('FATAL: checkpoint sha256 differs from the certified one in %s' % e['PROV_TR'])
for key, path in (('data_record_sha256', e['RECORD']), ('targets_table_sha256', e['TARGETS'])):
    if p.get(key) != sha(path): sys.exit('FATAL: %s now differs from the one the run was trained with (%s)' % (path, key))
print('[sidecar] arm=%s split=%s seed=%s encoding=%s drug_dimension=%s n_params=%s trained_at=%s  checkpoint and encoder inputs bound'
      % (s['arm'], s['split'], s['seed'], s['drug_encoding'], s['drug_dimension'], s['n_params'], str(s.get('commit'))[:7]))
PY

echo "[prereg] $N sections committed | [commit] $COMMIT | [node] $(hostname)"
echo "[task] T=$T  $TAG  arm=$ARM  encoding=$ENC  expect_conditions=$EXPECT_N  guidance=none  nfe=$NFE"
if [ "${DRYRUN:-0}" = "1" ]; then echo "[dryrun] guards passed for $TAG; nothing run"; exit 0; fi
python -u leakage_test_fm_step16.py "$SPLIT" "$CKPT" "$TAG" fm_gaussian "$NFE" euler

# --- post: outputs complete and consistent; sampler and harness prints match the arm; provenance ---
python - <<'PY'
import datetime, hashlib, json, os, re, subprocess, sys
import numpy as np
e = os.environ
tag = e['TAG']; expect_n = int(e['EXPECT_N'])
v = 'tahoe_results/vectors_%s.npz' % tag; pc = 'tahoe_results/vectors_%s_pc.npz' % tag; js = 'tahoe_results/leakage_%s.json' % tag
for f in (v, pc, js):
    if not os.path.isfile(f) or os.path.getsize(f) == 0: sys.exit('FATAL: missing or empty ' + f)
d = np.load(v, allow_pickle=True)
n = len(d['cond'])
if n != expect_n: sys.exit('FATAL: %d conditions, data record expects %d for %s' % (n, expect_n, e['SPLIT']))
if len(set(map(str, d['cond']))) != n: sys.exit('FATAL: duplicate condition labels')
for k in ('true', 'A', 'B', 'C'):
    if not np.all(np.isfinite(d[k])): sys.exit('FATAL: non-finite %s' % k)
if float(np.asarray(d['B']).min()) < 0: sys.exit('FATAL: negative predicted expression')
p = np.load(pc, allow_pickle=True)
if len(p['pred']) != expect_n: sys.exit('FATAL: per-cell file has %d conditions' % len(p['pred']))
nc = [int(np.asarray(a).shape[0]) for a in p['pred']]
if max(nc) > 200: sys.exit('FATAL: per-cell population larger than the 200-cell cap: %d' % max(nc))
log = open('logger_files/s16ev_%s_%s.out' % (e['SLURM_ARRAY_JOB_ID'], e['SLURM_ARRAY_TASK_ID'])).read()
m = re.search(r'encoder arm detected from checkpoint: (\S+) \(memory_size=(\d+)\)', log)
if not m: sys.exit('FATAL: the sampler did not print the detected encoder arm')
if m.group(1) != 'mlp' or int(m.group(2)) != 0: sys.exit('FATAL: sampler detected arm %s memory_size %s, task expects mlp 0' % (m.group(1), m.group(2)))
a = re.search(r'checkpoint architecture: (\S+)', log)
if not a or a.group(1) != 'adaLN-Zero': sys.exit('FATAL: sampler architecture %r, task expects adaLN-Zero' % (a.group(1) if a else None))
de = re.search(r'drug encoding detected from checkpoint: (\S+) \(drug_dimension=(\d+)\)', log)
if not de or de.group(1) != e['ENC'] or int(de.group(2)) != 1569: sys.exit('FATAL: sampler drug encoding %r, task expects %s (1569)' % (de.group(0) if de else None, e['ENC']))
he = re.search(r'\[harness\] drug encoder = (\S+) \(drug_dimension=(\d+)\)', log)
if not he or he.group(1) != e['ENC'] or int(he.group(2)) != 1569: sys.exit('FATAL: harness drug encoder %r, task expects %s (1569)' % (he.group(0) if he else None, e['ENC']))
tg = re.search(r'\[targets\] .*shuffled order sha256 ([0-9a-f]{12})', log)
if not tg: sys.exit('FATAL: the encoder did not print its [targets] line')
g = re.search(r'\[step12\] guidance_w=(\S+)', log)
if not g: sys.exit('FATAL: the FM sampler did not print its guidance setting')
if g.group(1) != 'None': sys.exit('FATAL: guidance_w=%s for an unguided arm' % g.group(1))
sha = lambda q: hashlib.sha256(open(q, 'rb').read()).hexdigest()
side = json.load(open(e['SIDE'])); tr = json.load(open(e['PROV_TR']))
if tr.get('shuffled_order_sha256_prefix') != tg.group(1): sys.exit('FATAL: the shuffled order at sampling (%s) differs from training (%s)' % (tg.group(1), tr.get('shuffled_order_sha256_prefix')))
rec = dict(status='completed', tag=tag, task=int(e['SLURM_ARRAY_TASK_ID']), slurm_array_job=e['SLURM_ARRAY_JOB_ID'],
           split=e['SPLIT'], arm=e['ARM'], seed=int(e['SEED']), encoder_arm='mlp', use_adaln=True, fm_source='gaussian', cond_drop=0.0,
           drug_encoding=e['ENC'], drug_dimension=1569, n_params=side['n_params'], shuffled_order_sha256_prefix=tg.group(1),
           sampler='euler_ode', nfe=int(e['NFE']), guidance_w=None, guide_t_min=0.0, max_cells_per_cond=200,
           n_conditions=n, cells_min=min(nc), cells_max=max(nc), expect_conditions=expect_n,
           prereg=e['PREREG'], commit=e['COMMIT'], training_commit=side.get('commit'), training_provenance=e['PROV_TR'],
           checkpoint=e['CKPT'], checkpoint_sha256=tr['checkpoint_sha256'],
           vectors_npz=v, vectors_sha256=sha(v), per_cell_npz=pc, per_cell_sha256=sha(pc), leakage_json=js, leakage_sha256=sha(js),
           data_record=e['RECORD'], data_record_sha256=sha(e['RECORD']), targets_table=e['TARGETS'], targets_table_sha256=sha(e['TARGETS']),
           harness_sha256=sha('leakage_test_fm_step16.py'), harness_src_sha256=sha('leakage_test_fm_tahoe.py'), harness_base_sha256=sha('leakage_test_base_tahoe.py'),
           sampler_sha256=sha('sample_squidiff.py'), datasets_sha256=sha('Squidiff/scrna_datasets.py'), flow_matching_sha256=sha('Squidiff/flow_matching.py'),
           node=subprocess.run('hostname', shell=True, capture_output=True, text=True).stdout.strip(),
           completed_at=datetime.datetime.now(datetime.timezone.utc).isoformat())
json.dump(rec, open(e['PROV'], 'w'), indent=2)
print('[post] %s: %d conditions (record %d), cells %d-%d, finite, non-negative, encoding %s bound by sampler and harness, unguided' % (tag, n, expect_n, min(nc), max(nc), e['ENC']))
PY
echo "[$(date)] $TAG DONE"
