    (C_REW_BLIND, 'Q1_recipe_minus_mean_response_excess_group', GROUP, 'excess', 'recipe', 'mean_response'),
    (C_REW_VEH, 'secondary_excess_recipe_minus_control_paste_group', GROUP, 'excess', 'recipe', 'control_paste'),
    (C_REW_RT, 'secondary_excess_recipe_minus_ridge_train_group', GROUP, 'excess', 'recipe', 'ridge_train'),
