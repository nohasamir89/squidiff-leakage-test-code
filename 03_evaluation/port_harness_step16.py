#!/usr/bin/env python
"""port_harness_step16.py -- generate the Step 16 evaluation harness from the Step 15 one (PREREG_step16 section 9).

leakage_test_fm_tahoe.py (itself generated from the frozen sci-Plex harness by port_harness_step15.py) selects the drug
encoder from the checkpoint's first-layer width through a fixed table {1024: 'fingerprint', ...}. Step 16 adds two
encodings of the same width (1,569: fp_targets and its shuffled control), so the width alone cannot select the
encoder. The generated file leakage_test_fm_step16.py replaces that one block by a DRUG_ENCODER_DIMS lookup with the
arm's encoding named in SQUIDIFF_DRUG_ENCODING (asserted against the width); everything else - the sampler wrapper,
the guidance plumbing, the execution of leakage_test_base_tahoe.py with the (line, plate) paired control - stays
byte-identical, so the Step 16 arrays are produced by exactly the Step 15b procedure.

Every anchor must occur exactly once, otherwise nothing is written. The generated file carries a header with the
source name and sha256; eval_step16_tahoe.sh refuses a stale file.
Usage:  python port_harness_step16.py            (from the repository root; prints a unified diff)
"""
import difflib
import hashlib
import os
import sys

FM_SRC, FM_DST = 'leakage_test_fm_tahoe.py', 'leakage_test_fm_step16.py'

FM_EDITS = [
    ("_name = {1024: 'fingerprint', 55: 'pathway', 1079: 'both',\n"
     "         196: 'chemvae', 1220: 'fp_chemvae'}.get(_dd)\n"
     "if _name is None:\n"
     "    sys.exit('FATAL: inferred drug_dimension %d is not a known encoding' % _dd)\n",
     "# Step 16 (PREREG_step16_tahoe_targets.md section 9): the width is looked up in DRUG_ENCODER_DIMS; two Step 16\n"
     "# encodings share the width 1,569, so the launcher names the arm's encoding in SQUIDIFF_DRUG_ENCODING, asserted\n"
     "# against the width (the patched sample_squidiff.py applies the same rule when it builds the model).\n"
     "from Squidiff.scrna_datasets import DRUG_ENCODER_DIMS as _DIMS16\n"
     "_cands = sorted(k for k, v in _DIMS16.items() if v == _dd and k != 'fingerprint_s10')\n"
     "_env = _os.environ.get('SQUIDIFF_DRUG_ENCODING')\n"
     "if _env is not None:\n"
     "    if _env not in _DIMS16:\n"
     "        sys.exit('FATAL: SQUIDIFF_DRUG_ENCODING=%r is not a known encoding %s' % (_env, sorted(_DIMS16)))\n"
     "    if _DIMS16[_env] != _dd:\n"
     "        sys.exit('FATAL: SQUIDIFF_DRUG_ENCODING=%r has width %d, the checkpoint has %d' % (_env, _DIMS16[_env], _dd))\n"
     "    _name = _env\n"
     "elif len(_cands) == 1:\n"
     "    _name = _cands[0]\n"
     "elif not _cands:\n"
     "    sys.exit('FATAL: inferred drug_dimension %d is not a known encoding %s' % (_dd, _DIMS16))\n"
     "else:\n"
     "    sys.exit('FATAL: drug_dimension %d is shared by %s; set SQUIDIFF_DRUG_ENCODING' % (_dd, _cands))\n"),
]


def sha256(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def port(src, dst, edits):
    text = open(src).read()
    for old, new in edits:
        n = text.count(old)
        if n != 1:
            sys.exit('FATAL: anchor found %d times in %s (expected 1):\n%s' % (n, src, old))
        text = text.replace(old, new)
    header = ('# GENERATED by port_harness_step16.py from %s (sha256 %s) -- do not edit; re-run the port script.\n'
              % (src, sha256(src)))
    out = header + text
    open(dst, 'w').write(out)
    diff = difflib.unified_diff(open(src).read().splitlines(), out.splitlines(), src, dst, lineterm='', n=1)
    print('\n'.join(diff))
    print('[port] wrote %s (%d lines, sha256 %s)\n' % (dst, out.count('\n'), sha256(dst)))


if __name__ == '__main__':
    if not os.path.isfile(FM_SRC):
        sys.exit('FATAL: run from the repository root; missing %s' % FM_SRC)
    port(FM_SRC, FM_DST, FM_EDITS)
